// contract.ts — что обязан уметь ЛЮБОЙ движок просмотра.
//
// Зачем отдельным файлом. До этого контракт существовал только комментарием в index.ts,
// а обвязка была типизирована КОНКРЕТНЫМ классом три.js (`Record<string, () => Viewer>`).
// Пока реализация одна, разницы не видно; второй движок упирается в неё сразу:
//
// 1. `Viewer` несёт поля `renderer: THREE.WebGLRenderer`, `_draco: DRACOLoader`,
//    `scene: THREE.Scene`. Структурная совместимость требует их и от чужой реализации —
//    то есть движок на Babylon.js обязан был бы завести у себя рендерер три.js.
// 2. `CameraState` носил `THREE.Vector3`. Даже ДАННЫЕ, которыми обмениваются два
//    вьюпорта, имели форму три.js: чужой реализации пришлось бы тянуть три.js ради
//    трёх чисел.
// 3. Комментарий разошёлся с делом: обвязка зовёт `setExposure()`, а в списке контракта
//    его не было. Движок, написанный строго по комментарию, молча остался бы без
//    экспозиции — и это выяснилось бы уже на экране.
//
// Проверка «шов настоящий?» из `ROADMAP.md` §5g теперь выполняется компилятором:
// реализация объявляет `implements ViewerLike`, и расхождение — ошибка сборки, а не
// находка на живой модели.
//
// Здесь НЕТ ни одного импорта из три.js — это и есть смысл файла.

/** Три числа. Не `THREE.Vector3`: обмен между вьюпортами — это данные, а не объекты движка. */
export interface Vec3 {
  x: number;
  y: number;
  z: number;
}

/**
 * Состояние камеры, которым обмениваются два вьюпорта.
 *
 * Поля — не только позиция: near/far и пределы приближения входят в снимок потому, что
 * иначе окна расходятся на краях диапазона и разница настроек показа выглядит как
 * последствие оптимизации. Подробности — у `getCameraState()` в реализации.
 */
export interface CameraState {
  position: Vec3;
  target: Vec3;
  near: number;
  far: number;
  minDistance: number;
  maxDistance: number;
}

/** Что просмотрщику нужно знать о загрузке: ход дела и ракурс, который надо сохранить. */
export interface LoadOptions {
  onProgress?: ((event: ProgressEvent) => void) | undefined;
  camera?: CameraState | null;
  /**
   * Расширение исходного файла без точки — 'stl', 'ply' и так далее.
   *
   * Нужно потому, что модель приходит blob-адресом, а в нём расширения НЕТ: узнать формат
   * по адресу нельзя. Пусто или 'glb'/'gltf' — обычный путь.
   */
  format?: string | null;
}

/**
 * Файл, который лежит РЯДОМ с моделью: `.bin` с геометрией, картинка текстуры.
 * `.gltf` — не один файл, а корень пачки, и без соседей он показывается пустым.
 *
 * `path` — адрес ровно в том виде, в каком он написан внутри `.gltf` (`textures/wood.png`),
 * относительно самой модели. Не имя файла: две картинки могут зваться `basecolor.png` и
 * лежать в разных папках.
 */
export interface PackEntry {
  path: string;
  file: File | Blob;
}

/** Метрики модели для HUD. Считает их сам движок — по тому, что реально попало в сцену. */
export interface ViewerStats {
  triangles: number;
  vertices: number;
  drawCalls: number;
  materials: number;
  textures: number;
}

/**
 * Что напрашивается по содержимому модели, а не что в ней уже есть. Смешивать нельзя:
 * иначе значок «В модели» перестанет что-либо означать.
 */
export interface ViewerOpportunity {
  sharedMeshes: number;
  sharedNodes: number;
}

/** Что уже применено в ИСХОДНОЙ модели — по её собственному объявлению расширений. */
export interface ViewerDetection {
  draco: boolean;
  meshopt: boolean;
  ktx2: boolean;
  instance: boolean;
  opportunity: ViewerOpportunity;
}

export interface AnimationInfo {
  count: number;
  names: string[];
  index: number;
  duration: number;
}

/**
 * Уровни детализации модели: одна и та же вещь, сделанная автором в нескольких степенях
 * подробности. Переключение между ними — состояние ПОКАЗА, а не правка файла.
 *
 * `source` обязан доходить до интерфейса: 'extension' — автор связал уровни расширением,
 * это факт; 'names' и 'measured' — догадка по соседним узлам, и выдавать её за факт
 * нечестно. Разница между догадками в улике: у 'names' соседи ещё и подписаны «LOD»,
 * у 'measured' подписи нет вовсе и решило одно измерение.
 */
export interface LodInfo {
  count: number;
  source: 'extension' | 'names' | 'measured' | null;
  /** Имена узлов из файла. Переводу не подлежат — данные, а не интерфейс (Правило 8). */
  names: string[];
  /** Треугольников в каждом уровне: по ним человек и отличает уровни друг от друга. */
  triangles: number[];
  /** Показанный уровень: номер, `'all'` — все сразу, `null` — как в файле. */
  current: number | 'all' | null;
}

/**
 * Варианты материала — запасные цвета и отделки, между которыми модель умеет
 * переключаться (три окраски машины, четыре ремешка часов).
 *
 * Имена приходят ИЗ ФАЙЛА, их писал художник в своём редакторе, и переводу они не
 * подлежат — это данные, а не интерфейс (Правило 8). `current: null` означает вид,
 * записанный в файле как основной; подменять его первым именем из списка нельзя.
 */
export interface VariantInfo {
  count: number;
  names: string[];
  current: string | null;
}

/**
 * Чей свет показан. `count` — сколько источников принесла САМА модель
 * (KHR_lights_punctual); ноль означает, что пункт «из файла» предлагать нечем: у модели
 * без источников это темнота, а не замысел автора.
 *
 * Режимов три, и третий — тоже выбор, а не отсутствие выбора. `none` гасит ВЕСЬ свет,
 * включая окружение: так видно светящиеся карты и так модель рендерится чёрной.
 *
 * Режим — состояние ПОКАЗА, как уровень детализации и вариант. Файл он не меняет.
 */
export interface LightInfo {
  count: number;
  mode: 'studio' | 'file' | 'none';
}

/**
 * Камеры, которые автор положил в файл: он выбирал, откуда на модель смотреть, и это
 * такое же его решение, как уровни детализации или варианты материала.
 *
 * `current: null` — смотрим своей орбитальной камерой. Имена приходят ИЗ ФАЙЛА, пустое
 * имя остаётся пустым: подпись безымянной камере придумывает интерфейс, а не движок
 * (Правило 8).
 */
export interface CameraListInfo {
  count: number;
  names: string[];
  current: number | null;
}

/**
 * Источник события «камера двигалась». У три.js это OrbitControls, у другого движка —
 * что угодно своё; обвязке нужны ровно две операции, и требовать больше незачем.
 */
export interface CameraChangeSource {
  addEventListener(type: 'change', listener: () => void): void;
  removeEventListener(type: 'change', listener: () => void): void;
}

/**
 * Контракт движка просмотра.
 *
 * Время анимации задаётся СНАРУЖИ и абсолютным значением, а не приращением. Это
 * обязательное требование к любой реализации: два вьюпорта показывают одну модель до и
 * после, и разъехавшаяся на полкадра поза делает сравнение бессмысленным.
 *
 * Движок отвечает только за СВОИ ресурсы. Пустое состояние слота (очистка полотна при
 * сбросе) — забота обвязки, одинаковая для всех движков (`ViewportSlot.reset()`), чтобы
 * смена движка не меняла поведение действий вокруг него.
 */
/** Чем показывать модель. Порядок блендеровский: сетка → глина → материалы. */
export type DisplayMode = 'wire' | 'clay' | 'file';

export interface SnapshotOptions {
  /** Ширина в пикселях; не задана — как на экране. */
  width?: number;
  /** Высота в пикселях; не задана — как на экране. */
  height?: number;
  /** Цвет подложки CSS-строкой либо `null` — прозрачный фон. */
  background?: string | null;
}

export interface SnapshotResult {
  blob: Blob;
  /** НАСТОЯЩИЙ размер снимка: движок мог обрезать запрошенный по потолку видеокарты. */
  width: number;
  height: number;
}

export interface ViewerLike {
  /** Загрузить модель и вернуть управление, когда она готова к показу. */
  load(url: string, options?: LoadOptions): Promise<unknown>;
  getStats(): ViewerStats | null;
  getDetection(): ViewerDetection | null;
  /** Отрисовать ОДИН кадр. Цикл гонит обвязка — она же сводит два вьюпорта в один кадр. */
  renderFrame(): void;
  /** Навести камеру на модель. */
  frame(): void;
  getCameraState(): CameraState;
  applyCameraState(state: CameraState | null): void;
  controls: CameraChangeSource;
  setAnimationTime(seconds: number): void;
  playClip(index: number): void;
  getAnimationInfo(): AnimationInfo;
  /** Какие уровни детализации есть у модели; count === 0 — их нет. */
  getLodInfo(): LodInfo;
  /** Показать уровень (0 — самый подробный), 'all' — все, null — как в файле. */
  setLod(index: number | 'all' | null): boolean;
  /** Какие камеры положил в файл автор и через какую смотрим. */
  getCameraInfo(): CameraListInfo;
  /** Смотреть через камеру автора либо вернуться к своей орбитальной (null). */
  setCamera(index: number | null): boolean;
  /**
   * Части, откликающиеся на нажатие НА САЙТЕ (`KHR_node_selectability`), и показана ли
   * сейчас их обводка. Показ, а не исполнение: граф поведения мы не проигрываем.
   */
  getInteractivityInfo(): { count: number; names: string[]; shown: boolean };
  /** Обвести нажимаемые части или снять обводку. false = обводить нечего. */
  setInteractivityMarks(on: boolean): boolean;
  /**
   * Проигрывается ли граф поведения и почему нет. `refusal` не пуст — в графе есть узлы
   * или адреса, которых мы не знаем, и тогда интерактив не проигрывается ЦЕЛИКОМ:
   * половинчатое проигрывание хуже отсутствия.
   */
  getBehaviourInfo(): { playable: boolean; refusal: string[] };
  /**
   * Кому рассказать о нажатии на интерактивную часть.
   *
   * Поле, а не метод: у вьюера слушатель ровно один, и ставит его тот, кто им владеет.
   * Нужен он затем, что отклики бывают тихие — цвет лампы, сдвиг развёртки, анимация
   * через секунду, — и без слова человек не отличит промах от «не работает».
   */
  onInteractivePick?: ((part: { name: string; responded: boolean }) => void) | null;
  /** Есть ли у модели свой свет и чей сейчас показан. */
  getLightInfo(): LightInfo;
  /** Выбрать свет: студийный, авторский или никакой. false = своего света у модели нет. */
  setLightMode(mode: 'studio' | 'file' | 'none'): boolean;
  /** Какие варианты материала есть у модели; count === 0 — их нет вовсе. */
  getVariantInfo(): VariantInfo;
  /** Переключить вариант; null — вернуть основной вид из файла. false = не вышло. */
  setVariant(name: string | null): Promise<boolean>;
  /** Общая экспозиция обоих окон. В прежнем списке контракта её не было — см. шапку. */
  setExposure(value: number): void;
  /**
   * Чем показывать модель: её материалами ('file'), нашей глиной ('clay') или сеткой
   * ('wire'). РЕЖИМ ПОКАЗА, не правка: родные материалы возвращаются на место, в файл не
   * попадает ничего (Правило 11).
   */
  setDisplayMaterial(mode: DisplayMode): boolean;
  getDisplayMaterial(): DisplayMode;
  /**
   * Снимок текущего кадра как PNG — ровно того, что человек видит.
   *
   * Состав кадра здесь НЕ выбирается: материал, вариант, поза, камера, уровень и свет уже
   * выбраны в окне. Второй набор настроек показа разошёлся бы с первым, и человек получил
   * бы картинку, которой не видел.
   *
   * `background` — цвет подложки CSS-строкой; `null` даёт прозрачный фон. Размеры не
   * обещания: движок обрежет их по потолку видеокарты и вернёт НАСТОЯЩИЕ.
   *
   * Необязательный метод: движок без него просто не умеет снимать, и обвязка обязана это
   * назвать, а не показать неработающую кнопку (Правило 12).
   */
  snapshot?(options?: SnapshotOptions): Promise<SnapshotResult | null>;
  /** Есть ли у модели хоть одна текстура — по этому обвязка решает, предлагать ли глину. */
  hasTextures(): boolean;
  /**
   * Куда движку идти за файлом, которого нет в сети. Функция получает адрес, каким его
   * вывел загрузчик, и возвращает подменный (blob брошенного файла) либо `null` — тогда
   * адрес остаётся как был.
   *
   * Необязательный метод, и это осознанно: движок без него показывает пачку без текстур,
   * а не падает. Но такой движок обязан сказать о себе — обвязка проверяет наличие метода
   * и предупреждает, а не молчит (Правило 12: показанная возможность обязана работать,
   * а отсутствующая — быть названной).
   */
  setAssetResolver?(resolve: ((url: string) => string | null) | null): void;
  /** Имена файлов брошенной пачки — нужны модели, которая своих текстур не называет. */
  setPackFiles?(paths: string[] | null): void;
  dispose(): void;
}
