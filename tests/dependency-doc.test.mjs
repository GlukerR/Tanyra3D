// tests/dependency-doc.test.mjs — справка о зависимостях не расходится с фактом.
//
// ПОВОД (ревизия 2026-09-01, проход П1). У `docs/ЗАВИСИМОСТИ.md` в собственной шапке
// написано: «открывать и обновлять эту секцию при каждом изменении версии зависимости в
// package.json». Правило было, держать его было нечему — и документ разошёлся молча:
//
//   sharp                  в документе 0.33.5, установлено 0.35.3 (две минорные версии)
//   @gltf-transform/core   в документе 4.4.1,  установлено 4.4.2
//   @gltf-transform/cli    записи не было вовсе — а без него не работает KTX2
//   three                  записи не было вовсе — а это весь просмотр
//
// Последние две — хуже расхождения в номере. Справка, к которой приходят с вопросом «что
// сломается, если обновить», молчала о движке просмотра целиком.
//
// ЧТО СТЕРЕЖЁМ, И ПОЧЕМУ ИМЕННО ЭТО:
//
//   1. У каждой РАБОЧЕЙ зависимости есть своя запись. Рабочая уезжает пользователю в
//      установщике; про неё обязан быть ответ «зачем она и что будет, если убрать».
//   2. Номер в записи — УСТАНОВЛЕННЫЙ, а не тот, что был когда-то. Сверяем с
//      node_modules, а не с диапазоном в package.json: `^4.2.0` разрешает и 4.4.2, и
//      справка про «4.2» была бы формально не противоречащей и при этом неверной.
//   3. Сборочные зависимости записи НЕ требуют (их не видит пользователь), но если запись
//      есть — номер в ней обязан быть верным. Половина правды хуже её отсутствия.
//
// ЧЕГО ЗДЕСЬ НЕТ: проверки СОДЕРЖАНИЯ записи. Что текст описывает библиотеку правдиво,
// автоматически не проверить — за это отвечает ревизия глазами. Здесь только то, что
// проверяемо: запись есть, номер верен.
//
// ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ФАЙЛА БЫЛА БЕСПОЛЕЗНА, и поймала её собственная проба на
// красноту. Она искала номер ПОДСТРОКОЙ ПО ВСЕМУ РАЗДЕЛУ и имя пакета — подстрокой по
// заголовку. Обе ошибки давали зелёное на сломанном:
//
//   — номер 0.35.3 упомянут в разделе sharp ещё и в исторической сноске («стояло 0.33.5
//     при установленной 0.35.3»), поэтому откат объявленной версии на 0.33.5 проверку
//     проходил;
//   — `запись('three')` при удалённом заголовке про three спокойно находила
//     `@types/three` — имя одного пакета является подстрокой имени другого.
//
// Отсюда нынешняя форма: заголовок разбирается на пары «имя (vномер)» ТОЧНО, и сверяется
// именно объявленный номер, а не любое упоминание числа поблизости.
//
// ПРОБА НА КРАСНОТУ (пройдена 2026-09-01, после переписывания): версия sharp в заголовке
// возвращена на 0.33.5 → краснеет сверка номеров и называет оба; удалён заголовок записи
// про three → краснеет проверка полноты и называет пакет.

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ДОК = 'docs/ЗАВИСИМОСТИ.md';
const текст = fs.readFileSync(path.join(root, ДОК), 'utf8');
// Второй документ с теми же номерами и тем же правилом «сверять при каждой смене версии».
// Добавлен ревизией 2026-09-01: он ЗНАЛ про расхождение sharp ещё 18 августа и указывал за
// подробностями в ЗАВИСИМОСТИ.md, где число оставалось старым. Два документа расходились
// друг с другом, и более свежий ссылался на устаревший.
const ДОК2 = 'docs/ИСТОЧНИКИ.md';
const текст2 = fs.readFileSync(path.join(root, ДОК2), 'utf8');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

/** Установленная версия пакета. `null` — пакета нет на диске (свежий клон без установки). */
function установлено(имя) {
  try {
    return JSON.parse(fs.readFileSync(path.join(root, 'node_modules', имя, 'package.json'), 'utf8')).version;
  } catch {
    return null;
  }
}

/**
 * Пары «имя пакета → объявленный номер», собранные из ЗАГОЛОВКОВ записей.
 *
 * Разбираем точно, а не поиском подстроки: имя одного пакета бывает подстрокой другого
 * (`three` внутри `@types/three` и `three-gltf-extensions`), и подстрочный поиск молча
 * подсовывал соседнюю запись вместо отсутствующей.
 *
 * Один заголовок может называть ДВА пакета — «typescript (v7.0.2) + @types/node
 * (v26.2.0)». Это законно: их версии двигаются вместе, и разводить записи значило бы
 * дублировать текст. Поэтому из заголовка берутся ВСЕ пары, а не первая.
 */
function объявлено() {
  const out = new Map();
  for (const [строка] of текст.matchAll(/^### Компонент:.*$/gm)) {
    for (const [, имя, версия] of строка.matchAll(/([@a-zA-Z0-9._/-]+)\s*\(v([^)]+)\)/g)) {
      if (!out.has(имя)) out.set(имя, версия.trim());
    }
  }
  return out;
}

const ОБЪЯВЛЕНО = объявлено();
const РАБОЧИЕ = Object.keys(pkg.dependencies || {});
const СБОРОЧНЫЕ = Object.keys(pkg.devDependencies || {});

describe('справка о зависимостях полна', () => {
  for (const имя of РАБОЧИЕ) {
    it(`${имя} — есть своя запись`, () => {
      expect(
        ОБЪЯВЛЕНО.has(имя),
        `${имя} — рабочая зависимость, она уезжает пользователю в установщике, а в ${ДОК} про неё нет записи. `
        + 'Завести раздел «### Компонент: имя (vномер)» с ответом на два вопроса: зачем она и что будет, если убрать.',
      ).toBe(true);
    });
  }
});

describe('номера в справке — установленные, а не вчерашние', () => {
  for (const имя of [...РАБОЧИЕ, ...СБОРОЧНЫЕ]) {
    const объявленная = ОБЪЯВЛЕНО.get(имя);
    const версия = установлено(имя);
    // Сборочная без записи — законно (её не видит пользователь). Пакета нет на диске —
    // сверять не с чем: мы сверяем с фактом установки, а не с диапазоном в package.json.
    const проверяем = typeof объявленная === 'string' && typeof версия === 'string';
    it(`${имя} — номер в справке совпадает с установленным${проверяем ? '' : ' [нечего сверять]'}`, () => {
      if (!проверяем) return;
      expect(
        объявленная,
        `${имя}: ${ДОК} объявляет ${объявленная}, а установлено ${версия}. `
        + 'Шапка документа требует обновлять запись при КАЖДОЙ смене версии — поправить номер и перечитать текст рядом: '
        + 'вместе с версией обычно устаревает и описание того, как мы библиотеку используем.',
      ).toBe(версия);
    });
  }
});


describe('таблица установленного в ИСТОЧНИКИ.md совпадает с деревом', () => {
  // Строки вида «| `пакет` | 4.4.2 | зачем | ссылка |». Разбираем только первые две клетки:
  // остальное — проза, и лезть в неё сторожу нечего.
  const объявлено = new Map();
  for (const [, имя, версия] of текст2.matchAll(/^\|\s*`([@a-zA-Z0-9._/-]+)`\s*\|\s*([0-9][^|\s]*)\s*\|/gm)) {
    объявлено.set(имя, версия.trim());
  }

  it('таблица вообще разобралась', () => {
    // Формат таблицы поменяли — сторож стал бы зелёным и пустым. Порог держит его честным.
    expect(объявлено.size, `в ${ДОК2} не нашлось ни одной строки «| \`пакет\` | версия |» — разбор таблицы сломался`)
      .toBeGreaterThanOrEqual(5);
  });

  for (const имя of [...Object.keys(pkg.dependencies || {}), ...Object.keys(pkg.devDependencies || {})]) {
    const версия = установлено(имя);
    const указано = объявлено.get(имя);
    const проверяем = typeof указано === 'string' && typeof версия === 'string';
    it(`${имя} — номер в таблице совпадает с установленным${проверяем ? '' : ' [в таблице нет]'}`, () => {
      if (!проверяем) return;
      expect(
        указано,
        `${имя}: ${ДОК2} называет ${указано}, установлено ${версия}. Шапка того документа требует `
        + 'сверять при каждой смене версии в package.json.',
      ).toBe(версия);
    });
  }
});
