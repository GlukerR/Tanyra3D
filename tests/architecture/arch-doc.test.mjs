//
// ПОВОД (ревизия 2026-09-01, проход П4). §5 «Data flow (five phases)» описывает работу
// движка, и описывает верно: пять фаз, их имена и порядок совпадают с `core/engine.mts`
// до буквы. Кроме одной строки — потолок автофикса был назван `profile.allowFixSafety`,
// то есть полем ПЛОЩАДКИ. Такого поля нет ни в одном профиле, и ни одна строка кода его
// не читает. Настоящий потолок — общая для движка константа `AUTOFIX_MAX_TIER`
// (`core/contract.mts`), а обойти её можно только флагом `force` из `canFix()` самого
// правила.
//
// Цена такой ошибки не в неточности, а в потерянном дне: заводящий новую площадку впишет
// `allowFixSafety` в профиль и будет смотреть, почему оно не работает.
//
// ЧТО СТЕРЕЖЁМ:
//
//   1. Каждое `profile.<поле>`, названное в §5, есть хотя бы у одного профиля. Именно §5,
//      а не весь документ: §4 честно помечен «design sketches — not implementation», и
//      называть там будущие поля — его прямая работа.
//   2. Число фаз в документе совпадает с числом фаз в движке. Имена НЕ сверяем: в
//      документе они английские заглавными (ANALYZE), в коде — строчные и иногда другой
//      формы (`analysis`). Требовать совпадения написания значило бы завести третий список
//      имён, который сам станет источником расхождения.
//
// ПРОБА НА КРАСНОТУ (пройдена 2026-09-01): вернул `profile.allowFixSafety` в §5 — краснеет
// проверка 1 и называет поле; дописал в §5 шестую фазу — краснеет проверка 2 и называет
// оба числа.

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const ДОК = 'docs/ARCHITECTURE.md';
const текст = fs.readFileSync(path.join(root, ДОК), 'utf8');
const движок = fs.readFileSync(path.join(root, 'core', 'engine.mts'), 'utf8');

/** Кусок документа от одного заголовка `## N.` до следующего. */
function раздел(заголовок) {
  const от = текст.indexOf(заголовок);
  if (от === -1) return '';
  const дальше = текст.indexOf('\n## ', от + заголовок.length);
  return текст.slice(от, дальше === -1 ? текст.length : дальше);
}

/**
 * Раздел без строк-сносок.
 *
 * Сноска в этих документах — строка, начинающаяся с `>`: статус, поправка, «раньше здесь
 * стояло». В ней ЦИТИРУЮТ неверное имя, чтобы объяснить, почему оно неверное, — и первая
 * редакция этого сторожа покраснела ровно на такой цитате, то есть на объяснении
 * собственной находки. Описываемый механизм живёт в основном тексте, сноска описывает
 * ИСТОРИЮ, и смешивать их нельзя.
 */
const безСносок = (кусок) => кусок
  .split(/\r?\n/)
  .filter((l) => !l.trimStart().startsWith('>'))
  .join('\n');

const ПЯТЬ_ФАЗ = безСносок(раздел('## 5. Data flow'));

describe('§5 не называет полей профиля, которых нет', () => {
  const поля = new Set();
  for (const f of fs.readdirSync(path.join(root, 'profiles')).filter((x) => x.endsWith('.json'))) {
    const j = JSON.parse(fs.readFileSync(path.join(root, 'profiles', f), 'utf8'));
    for (const k of Object.keys(j)) поля.add(k);
  }

  it('раздел найден', () => {
    // Заголовок переименовали — сторож стал бы зелёным и пустым.
    expect(ПЯТЬ_ФАЗ.length, `в ${ДОК} не нашёлся раздел «## 5. Data flow»`).toBeGreaterThan(200);
  });

  const названные = [...new Set([...ПЯТЬ_ФАЗ.matchAll(/\bprofile\.([A-Za-z][A-Za-z0-9_]*)/g)].map((m) => m[1]))];
  for (const имя of названные) {
    it(`profile.${имя} — такое поле у профилей есть`, () => {
      expect(
        поля.has(имя),
        `${ДОК} §5 описывает механизм через «profile.${имя}», а такого поля нет ни в одном profiles/*.json. `
        + 'Либо поле называется иначе, либо механизм вообще не в профиле — проверить по core/ и поправить документ. '
        + '§4 под это правило не подпадает: он помечен design sketch.',
      ).toBe(true);
    });
  }
});

describe('число фаз в документе и в движке совпадает', () => {
  it('пять там и пять здесь', () => {
    const вДоке = new Set([...ПЯТЬ_ФАЗ.matchAll(/^\s*PHASE (\d)/gm)].map((m) => m[1]));
    const вДвижке = new Set([...движок.matchAll(/type:\s*'phase',\s*phase:\s*(\d)/g)].map((m) => m[1]));
    expect(вДоке.size, 'в §5 не разобрана ни одна строка «PHASE N» — формат раздела сменился')
      .toBeGreaterThan(0);
    expect(
      [...вДоке].sort(),
      `${ДОК} §5 описывает ${вДоке.size} фаз(ы), а core/engine.mts объявляет ${вДвижке.size}. `
      + 'Фазу добавили или убрали, а документ об этом не узнал.',
    ).toEqual([...вДвижке].sort());
  });
});
