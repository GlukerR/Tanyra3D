// tests/lod-detect.test.mjs — уровни узнаются ИЗМЕРЕНИЕМ, а не именем узла.
//
// ЗАКАЗ (Александр, 2026-08-26). «мы должны распределять не по названию их. а по
// размерам модели (размерам текстур или размерам самого меша) Только это точно
// определяет какой лод». И про самый грубый уровень: «у нас есть модель где колодец в
// конце становится просто плейном вдалеке. мы должны его тоже ловить и понимать как
// лод, хоть и габарит вообще стал другим».
//
// ПОЧЕМУ ЗАГОТОВКИ, А НЕ МОДЕЛИ ИЗ КОРПУСА. Спорный случай здесь — модель БЕЗ подписи
// «LOD» в именах, а такой в корпусе нет ни одной: Stone Well подписан, остальные уровней
// не несут. Ждать, пока подходящая модель появится, значит не проверять правило вовсе.
// Вдобавок урок 2026-08-27: браузерный тест, опёртый на образцы Khronos, покраснел на CI,
// потому что в git их нет и не будет (Правило 0). Заготовки строятся здесь же, идут в
// node-контексте за секунды и работают на любом клоне.
//
// Модели из корпуса при этом никуда не делись: Stone Well обоих видов и CarConcept
// сторожат ту же логику на настоящих файлах — tests/viewer-regression.browser.test.mjs.
//
// ЧТО ИМЕННО СТОРОЖИМ. Не «находит уровни» — это половина. Вторая половина важнее:
// НЕ находит их там, где их нет. Набор частей модели — это тоже соседние узлы с
// геометрией, и принять части за уровни значило бы решить за автора (Правило 11).
// Поэтому половина разделов ниже требует именно `null`.

import { describe, it, expect } from 'vitest'
import * as THREE from 'three'

import { detectLods, showLod } from '../ui/viewer/lod.js'

/** Картинка нужного размера. Пикселей в ней — вторая мера подробности. */
const texture = (px) => new THREE.Texture({ width: px, height: px })

/**
 * Узел с заданной подробностью, габаритом и местом.
 *
 * Подробность задаём числом сегментов куба: треугольников выходит ровно 12·seg².
 * seg 4 → 192, seg 2 → 48, seg 1 → 12. Между соседними ступенями кратность 4 — как в
 * настоящих уровнях (у Stone Well шаги 6.8×, 4.4×, 4.6×, 3.8×).
 */
function node(name, { seg = 1, size = [1, 1, 1], at = [0, 0, 0], px = 0 } = {}) {
  const material = new THREE.MeshStandardMaterial()
  if (px) material.map = texture(px)
  const mesh = new THREE.Mesh(new THREE.BoxGeometry(...size, seg, seg, seg), material)
  mesh.name = name
  mesh.position.set(...at)
  return mesh
}

/** Плоский биллборд: тот самый «колодец, ставший плейном». */
function billboard(name, { w = 1, h = 1, at = [0, 0, 0] } = {}) {
  const mesh = new THREE.Mesh(new THREE.PlaneGeometry(w, h), new THREE.MeshStandardMaterial())
  mesh.name = name
  mesh.position.set(...at)
  return mesh
}

const scene = (...children) => {
  const group = new THREE.Group()
  for (const c of children) group.add(c)
  return group
}

const detect = (group) => detectLods({ scene: group })

// ═══════════════════════════════════════════════════════════════════════════
// РАЗДЕЛ 1 · Уровни без подписи — то, ради чего всё и затевалось
// ═══════════════════════════════════════════════════════════════════════════

describe('уровни без слова LOD в именах', () => {
  it('три ступени в одной точке — узнаны измерением', async () => {
    const set = await detect(scene(
      node('well', { seg: 4 }),
      node('well_far', { seg: 2 }),
      node('Plane.003', { seg: 1 }),
    ))
    expect(set, 'уровни не найдены — распознавание опять держится на имени').toBeTruthy()
    // 'measured' — не придирка к слову: интерфейс по нему решает, называть находку
    // фактом или догадкой, и догадку без подписи выдавать за факт нельзя.
    expect(set.source).toBe('measured')
    // Порядок — от подробного к грубому, по измерению. Имена в нём не участвуют вовсе.
    expect(set.levels.map((l) => l.triangles)).toEqual([192, 48, 12])
    expect(set.levels.map((l) => l.name)).toEqual(['well', 'well_far', 'Plane.003'])
  })

  it('колодец, ставший плоским плейном, — тоже уровень', async () => {
    // Замер на Stone Well: самый грубый уровень 1.282 × 0.719 × 0.000 против
    // 1.302 × 0.705 × 1.302 у подробного. Схлопнулась не «третья» сторона, а одна из
    // двух горизонтальных — объём выброшен целиком, силуэт сохранён. Требовать
    // сохранности второго габарита значит не узнавать самый грубый уровень никогда.
    const set = await detect(scene(
      node('well', { seg: 4, size: [1.3, 0.7, 1.3] }),
      node('well2', { seg: 2, size: [1.3, 0.7, 1.3] }),
      billboard('well3', { w: 1.28, h: 0.72 }),
    ))
    expect(set, 'плоский уровень не узнан — габарит принят за чужой').toBeTruthy()
    expect(set.levels.map((l) => l.triangles)).toEqual([192, 48, 2])
  })

  it('витрина в ряд — уровни, а не раскладка частей', async () => {
    // Автор Stone Well выложил шесть уровней в ряд вдоль X с ровным шагом, чтобы
    // сравнить их рядом. Требовать общего места значило бы не узнать этот случай.
    const set = await detect(scene(
      node('a', { seg: 4, at: [0, 0, 0] }),
      node('b', { seg: 2, at: [2, 0, 0] }),
      node('c', { seg: 1, at: [4, 0, 0] }),
    ))
    expect(set, 'ряд с ровным шагом не узнан').toBeTruthy()
    expect(set.source).toBe('measured')
  })

  it('лестница по картинкам при одинаковой сетке — тоже уровни', async () => {
    // Вторая мера, названная Александром наравне с сеткой: бывает, что сетка та же, а
    // карта вчетверо меньше. По треугольникам такие уровни неразличимы вовсе.
    const set = await detect(scene(
      node('a', { seg: 2, px: 2048 }),
      node('b', { seg: 2, px: 1024 }),
      node('c', { seg: 2, px: 512 }),
    ))
    expect(set, 'уровни по размеру текстур не узнаны').toBeTruthy()
    expect(set.levels.map((l) => l.texturePixels)).toEqual([2048 * 2048, 1024 * 1024, 512 * 512])
  })
})

// ═══════════════════════════════════════════════════════════════════════════
// РАЗДЕЛ 2 · Части модели уровнями НЕ становятся
//
// Каждый случай ниже — обычная модель, каких большинство. Показать на ней панель
// «Похоже на уровни» и спрятать половину предмета значило бы решить за автора.
// ═══════════════════════════════════════════════════════════════════════════

describe('обычные части модели уровнями не считаются', () => {
  it('одинаковые куски (четыре колеса) — не уровни', async () => {
    const set = await detect(scene(
      node('wheel_fl', { seg: 2, at: [-1, 0, 1] }),
      node('wheel_fr', { seg: 2, at: [1, 0, 1] }),
      node('wheel_rl', { seg: 2, at: [-1, 0, -1] }),
      node('wheel_rr', { seg: 2, at: [1, 0, -1] }),
    ))
    expect(set, 'одинаковые части приняты за уровни').toBeNull()
  })

  it('части разного габарита — не уровни', async () => {
    const set = await detect(scene(
      node('body', { seg: 4, size: [2, 2, 2] }),
      node('mirror', { seg: 2, size: [0.5, 0.5, 0.5] }),
      node('bolt', { seg: 1, size: [0.2, 0.2, 0.2] }),
    ))
    expect(set, 'разные по размеру части приняты за уровни').toBeNull()
  })

  it('лестница подробности, но части стоят вразнобой — не уровни', async () => {
    // Уровни ЗАМЕЩАЮТ друг друга: одно место или ровный ряд. Части СКЛАДЫВАЮТСЯ в
    // предмет, и места у них свои, не прогрессия.
    const set = await detect(scene(
      node('a', { seg: 4, at: [0, 0, 0] }),
      node('b', { seg: 2, at: [1.5, 0, 0] }),
      node('c', { seg: 1, at: [5, 0, 0] }),
    ))
    expect(set, 'вразнобой расставленные части приняты за уровни').toBeNull()
  })

  it('двух неподписанных ступеней мало', async () => {
    // «Крупная часть плюс мелкая» есть в любой модели. Лестница из трёх ступеней
    // случайно не складывается, из двух — сплошь и рядом.
    const set = await detect(scene(
      node('frame', { seg: 4 }),
      node('glass', { seg: 1 }),
    ))
    expect(set, 'пара «крупное + мелкое» принята за уровни').toBeNull()
  })

  it('ступени слишком близкие по подробности — не уровни', async () => {
    // Уровень делают кратно грубее, иначе он не экономит ничего. Части отличаются
    // подробностью случайно и понемногу.
    const a = node('a', { seg: 4 })
    const b = node('b', { seg: 4 })
    // 192 против 150 — разница есть, кратности нет.
    b.geometry = new THREE.BoxGeometry(1, 1, 1, 5, 5, 2)
    const c = node('c', { seg: 4 })
    c.geometry = new THREE.BoxGeometry(1, 1, 1, 4, 4, 3)
    const set = await detect(scene(a, b, c))
    expect(set, 'близкие по подробности части приняты за уровни').toBeNull()
  })

  it('грубее сеткой, но крупнее картинкой — не уровень', async () => {
    // Обе меры обязаны смотреть в одну сторону. Узел с более грубой сеткой и БОЛЬШЕЙ
    // картой — не огрубление той же вещи, а другая вещь.
    const set = await detect(scene(
      node('a', { seg: 4, px: 1024 }),
      node('b', { seg: 2, px: 2048 }),
      node('c', { seg: 1, px: 512 }),
    ))
    expect(set, 'растущая текстура не помешала счесть узлы уровнями').toBeNull()
  })

  it('уровень шире подробного — не огрубление', async () => {
    const set = await detect(scene(
      node('a', { seg: 4, size: [2, 1, 0.5] }),
      node('b', { seg: 2, size: [2, 1, 0.5] }),
      node('c', { seg: 1, size: [2, 1.5, 0.1] }),
    ))
    expect(set, 'раздувшийся узел принят за уровень').toBeNull()
  })
})

// ═══════════════════════════════════════════════════════════════════════════
// РАЗДЕЛ 3 · Подпись «LOD» — улика, а не пропуск
//
// Имя больше ничего не решает, но и не выброшено: автор, подписавший узлы, сам сказал,
// что это уровни, и спорить с ним измерением незачем — меры те же, требования мягче.
// ═══════════════════════════════════════════════════════════════════════════

describe('имя как улика', () => {
  it('двух подписанных ступеней достаточно', async () => {
    const set = await detect(scene(
      node('well_LOD0', { seg: 4 }),
      node('well_LOD1', { seg: 1 }),
    ))
    expect(set, 'подписанная пара не узнана').toBeTruthy()
    expect(set.source).toBe('names')
    expect(set.levels.map((l) => l.triangles)).toEqual([192, 12])
  })

  it('та же пара без подписи уровнями не считается', async () => {
    // Прямое сравнение с предыдущим: разницу делает именно подпись, а не геометрия.
    const set = await detect(scene(
      node('well_a', { seg: 4 }),
      node('well_b', { seg: 1 }),
    ))
    expect(set).toBeNull()
  })

  it('подписанные узлы отбираются из общей толпы соседей', async () => {
    const set = await detect(scene(
      node('ground', { seg: 1, size: [10, 0.1, 10], at: [0, -1, 0] }),
      node('well_LOD0', { seg: 4 }),
      node('well_LOD1', { seg: 2 }),
    ))
    expect(set.source).toBe('names')
    expect(set.levels).toHaveLength(2)
    expect(set.levels.map((l) => l.name)).toEqual(['well_LOD0', 'well_LOD1'])
  })

  it('порядок решает подробность, а не номер в имени', async () => {
    // У автора Stone Well `LOD0` — самый грубый. Доверять номеру значило бы выстроить
    // список наоборот.
    const set = await detect(scene(
      node('w_LOD0', { seg: 1 }),
      node('w_LOD1', { seg: 4 }),
      node('w_LOD2', { seg: 2 }),
    ))
    expect(set.levels.map((l) => l.name)).toEqual(['w_LOD1', 'w_LOD2', 'w_LOD0'])
  })
})

// ═══════════════════════════════════════════════════════════════════════════
// РАЗДЕЛ 4 · Показ ничего не удаляет (Правило 11)
// ═══════════════════════════════════════════════════════════════════════════

describe('переключение — состояние показа', () => {
  it('«как в файле» у соседей показывает все уровни сразу', async () => {
    const root = scene(
      node('a', { seg: 4 }),
      node('b', { seg: 2 }),
      node('c', { seg: 1 }),
    )
    const set = await detect(root)

    showLod(set, root, 1)
    expect(root.children.map((o) => o.visible)).toEqual([false, true, false])

    // Именно так модель и приезжает: движок рисует все уровни друг сквозь друга, и
    // человек имеет право увидеть, что там на самом деле.
    showLod(set, root, null)
    expect(root.children.map((o) => o.visible)).toEqual([true, true, true])

    // И ни один узел никуда не делся — их прятали, а не удаляли.
    expect(root.children).toHaveLength(3)
  })
})

// ═══════════════════════════════════════════════════════════════════════════
// РАЗДЕЛ 5 · Кусок меша — не сосед
//
// Настоящая находка 2026-08-26, и найдена она этими же тестами на живой модели.
// `Dirty Cube 01.glb` — простейший куб. Загрузчик three.js разрезает меш из нескольких
// примитивов на отдельные `THREE.Mesh` и кладёт в группу, и куб приехал ТРЕМЯ кусками:
// 8 + 2 + 2 треугольника, у одного нет карт вовсе, все три в одной точке и с одним
// габаритом. То есть кусок прошёл ВСЕ геометрические проверки и объявился уровнем.
//
// Ни одна мера тут не спасает: куски одного меша и правда стоят в одном месте и правда
// разной подробности. Спасает только факт из файла — `parser.associations` помечает,
// чем объект был в glTF. Кусок несёт `primitives` и не несёт `nodes`.
// ═══════════════════════════════════════════════════════════════════════════

describe('куски одного меша уровнями не считаются', () => {
  /** Разметка загрузчика: чем каждый объект был в файле. */
  const withParser = (group, mark) => ({
    scene: group,
    parser: { associations: new Map(group.children.map((c, i) => [c, mark(i)])) },
  })

  it('три примитива одного меша — не уровни', async () => {
    // Ровно случай Dirty Cube: подробность лестницей, место одно, габарит один.
    const group = scene(
      node('Cube_1', { seg: 4 }),
      node('Cube_2', { seg: 2 }),
      node('Cube_3', { seg: 1 }),
    )
    const set = await detectLods(withParser(group, (i) => ({ meshes: 0, primitives: i })))
    expect(set, 'разрезанный по материалам меш принят за три уровня').toBeNull()
  })

  it('те же объекты как узлы файла — уровни', async () => {
    // Прямое сравнение: геометрия та же до последнего треугольника, разницу делает
    // только разметка загрузчика.
    const group = scene(
      node('Cube_1', { seg: 4 }),
      node('Cube_2', { seg: 2 }),
      node('Cube_3', { seg: 1 }),
    )
    const set = await detectLods(withParser(group, (i) => ({ nodes: i })))
    expect(set, 'узлы файла не узнаны').toBeTruthy()
    expect(set.levels).toHaveLength(3)
  })
})
