// ЗАВЕДЁН 2026-08-26 по находке Ф1-3 аудита (docs/АУДИТ_Ф1_результат.md).
//
// ЧТО ЗАМЕРЕНО. Ключи бюджетов, которые движок умеет проверять, перечислены в
// `BUDGET_SPEC` (assistant.mts): там сказано, как посчитать значение, в каких единицах
// его показать и каким ключом назвать. Профиль площадки эти ключи УПОТРЕБЛЯЕТ.
//
// Незнакомый ключ проваливается в тишину. Проба: профиль с `budgets.vertices` (порог с
// источником, всё по форме) дал в отчёте НОЛЬ проверок — ни отказа, ни строки в журнале,
// ни намёка. Файл выглядит рабочим и не сторожит ничего.
//
// Догадка контрибутора при этом законная: вершины движок И ПРАВДА меряет — `metric.vertices`
// есть в каталоге ядра, число видно в отчёте. Просто слой бюджетов о нём не знает.
//
// ПОЧЕМУ СТОРОЖ, А НЕ ПРЕДУПРЕЖДЕНИЕ В КОДЕ. Предупреждение нужно тоже, но у него есть
// вопрос без ответа: КУДА оно идёт. Профиль читается на сервере, а неверный ключ написал
// человек, которого в этот момент у экрана нет. Решать это попутно, в ходе аудита, —
// значит решать за Александра, как выглядит ошибка в интерфейсе. Здесь закрыт репозиторий;
// свои профили (папка рядом с настройками) остаются открытым вопросом — записан в отчёте.
//
// ПРОБА НА КРАСНОТУ пройдена: добавил `budgets.vertices` во встроенный профиль — краснеет,
// и сообщение называет и ключ, и файл, и список известных.

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Ключи, которые движок умеет проверять, — ЧИТАЕМ ИЗ `BUDGET_SPEC`, а не переписываем.
 *
 * Своя копия здесь была бы тем же дублем факта, который фазы Ф2 и Ф3 убирали из кода:
 * добавят седьмой бюджет — сторож подхватит его сам.
 */
function известныеКлючи() {
  const src = fs.readFileSync(path.join(ROOT, 'assistant.mts'), 'utf8');
  const от = src.indexOf('const BUDGET_SPEC');
  expect(от, 'в assistant.mts не найден BUDGET_SPEC — проверка ослепла; если объявление '
    + 'переименовали, поправь якорь здесь').toBeGreaterThan(-1);
  const блок = src.slice(от, src.indexOf('\n};', от));
  return [...блок.matchAll(/^ {2}([A-Za-z][A-Za-z0-9]*):/gm)].map((m) => m[1]);
}

const ПРОФИЛИ = fs.readdirSync(path.join(ROOT, 'profiles')).filter((f) => f.endsWith('.json'));

describe('пороги площадки называют то, что движок умеет проверять', () => {
  const известные = известныеКлючи();

  it('список известных бюджетов непуст', () => {
    expect(известные.length, 'BUDGET_SPEC пуст — сторож ниже пропустит что угодно')
      .toBeGreaterThan(3);
  });

  for (const файл of ПРОФИЛИ) {
    it(`${файл}: ни одного бюджета мимо BUDGET_SPEC`, () => {
      const p = JSON.parse(fs.readFileSync(path.join(ROOT, 'profiles', файл), 'utf8'));
      const чужие = Object.keys(p.budgets || {}).filter((k) => !известные.includes(k));
      expect(чужие,
        `${файл}: порог(и) ${чужие.join(', ')} движку неизвестны и будут выброшены МОЛЧА — `
        + `ни отказа, ни строки в журнале. Известные: ${известные.join(', ')}`)
        .toEqual([]);
    });
  }

  it('обратная сторона: каждый известный бюджет где-то употребляется', () => {
    // Иначе `BUDGET_SPEC` обрастает мёртвыми записями: код умеет проверять порог,
    // которого не ставит ни одна площадка, и никто этого не замечает.
    const употреблены = new Set();
    for (const файл of ПРОФИЛИ) {
      const p = JSON.parse(fs.readFileSync(path.join(ROOT, 'profiles', файл), 'utf8'));
      for (const k of Object.keys(p.budgets || {})) употреблены.add(k);
    }
    const мёртвые = известные.filter((k) => !употреблены.has(k));
    expect(мёртвые,
      `движок умеет проверять ${мёртвые.join(', ')}, но ни одна площадка такого порога `
      + 'не ставит. Либо порог нужен и его стоит объявить, либо запись в BUDGET_SPEC мёртвая')
      .toEqual([]);
  });
});
