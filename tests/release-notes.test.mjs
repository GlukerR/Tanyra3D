// tests/release-notes.test.mjs — выпуск без описания блокирует следующий выпуск.
//
// ЗАКАЗ Александра, 2026-09-03: «нужно сделать тест, который не будет разрешать выпускать
// новую версию программы, пока изменения версии не записываются нормально на гите. потому
// что версия 27 опять просто Full Changelog: v0.2.26...v0.2.27. если там просто устранение
// простых багов, то это так и должно быть записано. а если нечего нельзя вообще записать,
// то с чего у нас происходит изменение версии».
//
// ПОЧЕМУ СТОРОЖ, А НЕ ВНИМАТЕЛЬНОСТЬ. Правило «описание ставится командой и проверяется
// глазами» записано в CLAUDE.md и нарушено ШЕСТЬ раз: v0.2.9, v0.2.10, v0.2.12, v0.2.13,
// v0.2.22 и снова v0.2.27. Каждый раз потому, что `gh release create` считался достаточным,
// а GitHub молча подставляет свою «Full Changelog» — и человек видит ссылку на список
// коммитов вместо ответа на вопрос «что изменилось». Правило, нарушенное шесть раз, надо
// не повторять громче, а поставить на проверку.
//
// КАК ЭТО ОСТАНАВЛИВАЕТ ВЫПУСК. Набор гоняется ПОСЛЕ подъёма версии и до отправки тега
// (Правило 0, цепочка законченной версии). Красный тест — красный прогон — тега нет.
// Проверяются УЖЕ ОПУБЛИКОВАННЫЕ выпуски: описание пишется после создания выпуска, поэтому
// сторож ловит не тот выпуск, который делается сейчас, а тот, который забыли в прошлый раз.
// Забыл — исправь прошлое, потом выпускай новое.
//
// ГРАНИЦА. Проверяются выпуски НАЧИНАЯ С ТОГО, при котором правило появилось. До него
// описаний не было ни у одного, и дописывать их сегодня значило бы сочинять историю: что
// именно менялось в v0.1.0, сейчас честно не восстановить.
//
// ПОЧЕМУ ПРОПУСК БЕЗ `gh` НЕ ДЫРА. Без `gh` выпуск невозможен физически — нечем ни создать
// выпуск, ни поставить описание. Машина, которая не может выпускать, не может и нарушить.
// Именно поэтому пропуск здесь не «тест не сработал», а «выпускать отсюда никто не будет».
//
// ПРОБА НА КРАСНОТУ (пройдена 2026-09-03): до правки описания v0.2.27 сторож называл её
// поимённо; после правки — зелёный. Второй заход: понизил `ПЕРВЫЙ_С_ПРАВИЛОМ` до v0.0.10 —
// покраснел на всех выпусках старой эпохи, то есть граница действительно работает.

import { describe, it, expect } from 'vitest';
import { execFileSync } from 'node:child_process';

/**
 * Первый выпуск, к которому правило применимо. v0.2.9 — 2026-08-22, ближайший к слову
 * Александра «очень кратко список изменений и всё» (2026-08-23). Всё, что старше, вышло
 * без правила.
 */
const ПЕРВЫЙ_С_ПРАВИЛОМ = [0, 2, 9];

const число = (tag) => tag.replace(/^v/, '').split('.').map((n) => parseInt(n, 10) || 0);

const новееПравила = (tag) => {
  const [a, b, c] = число(tag);
  const [x, y, z] = ПЕРВЫЙ_С_ПРАВИЛОМ;
  if (a !== x) return a > x;
  if (b !== y) return b > y;
  return c >= z;
};

function gh(args) {
  return execFileSync('gh', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}

/**
 * Выпуски вместе с телами — ОДНИМ запросом через API.
 *
 * `gh release list --json body` не существует: у списка такого поля нет, и попытка молча
 * роняла команду. Сторож при этом ЗЕЛЕНЕЛ, пропустив себя как «нет gh» — то есть первым же
 * запуском показал, чем опасен пропуск без разбора причины. Отсюда разделение ниже.
 */
let выпуски = null;
let можноВыпускать = false;
let почемуМолчим = null;
try {
  gh(['--version']);
} catch (err) {
  почемуМолчим = `gh не установлен: ${String(err?.message || err).split(/\r?\n/)[0]}`;
}
if (почемуМолчим === null) {
  // ПРИЗНАК — НЕ «ЕСТЬ ЛИ gh», А «МОЖНО ЛИ ОТСЮДА ВЫПУСКАТЬ».
  //
  // Первая редакция считала достаточным наличие `gh` — и уронила CI (прогон 33863621070):
  // на раннере он установлен, но без доступа к API, и сторож честно объявил себя слепым.
  // Формально верно, по сути нет: с раннера описаний никто не ставит, и выпуск оттуда
  // невозможен ровно так же, как с машины без `gh`.
  //
  // Права — это `gh auth status`. Есть права: сторож ОБЯЗАН видеть выпуски, и если не
  // видит — красный. Нет прав: выпускать неоткуда, молчим.
  try {
    gh(['auth', 'status']);
    можноВыпускать = true;
  } catch (err) {
    почемуМолчим = `gh без доступа к GitHub: ${String(err?.message || err).split(/\r?\n/)[0]}`;
  }
}
if (можноВыпускать) {
  try {
    выпуски = JSON.parse(gh(['api', 'repos/{owner}/{repo}/releases', '--paginate']))
      .map((r) => ({ tagName: r.tag_name, body: r.body }));
  } catch (err) {
    почемуМолчим = String(err?.message || err).split(/\r?\n/)[0];
  }
}

/**
 * Что считается ОТСУТСТВИЕМ описания.
 *
 * «Full Changelog» подставляет сам GitHub, когда тела нет. Ссылка на список коммитов —
 * не ответ на вопрос «что изменилось»: читатель выпуска и читатель кода разные люди.
 */
const пусто = (body) => {
  const строки = String(body || '')
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean)
    .filter((s) => !/^\*{0,2}full changelog/i.test(s));
  return строки.length === 0;
};

describe('у каждого выпуска есть описание', () => {
  it.skipIf(!выпуски)('ни один опубликованный выпуск не остался с одной «Full Changelog»', () => {
    const немые = выпуски
      .filter((r) => новееПравила(r.tagName))
      .filter((r) => пусто(r.body))
      .map((r) => r.tagName);
    expect(
      немые,
      'выпуск опубликован без описания — поставить его командой `gh release edit <тег> --notes …` '
      + 'и проверить глазами `gh release view <тег> --json body`. Нечего написать — значит и '
      + 'версию поднимать было не за что (Александр, 2026-09-03)',
    ).toEqual([]);
  });

  it.skipIf(!выпуски)('описание — список, а не сплошной текст', () => {
    // Правило 0: «очень кратко список изменений и всё». Строка на изменение.
    const несписки = выпуски
      .filter((r) => новееПравила(r.tagName) && !пусто(r.body))
      .filter((r) => !String(r.body).split('\n').some((s) => /^\s*[-*]\s+\S/.test(s)))
      .map((r) => r.tagName);
    expect(несписки, 'описание выпуска пишется списком: строка на изменение').toEqual([]);
  });

  it('граница правила названа, а не угадывается', () => {
    // Сторож самому себе: без границы тест либо молчит обо всём, либо требует сочинить
    // историю старых выпусков.
    expect(ПЕРВЫЙ_С_ПРАВИЛОМ).toHaveLength(3);
    expect(новееПравила('v0.2.9'), 'выпуск, с которого правило действует, обязан проверяться').toBe(true);
    expect(новееПравила('v0.2.8'), 'выпуск до правила проверяться не должен').toBe(false);
    expect(новееПравила('v0.3.0'), 'следующая крупная версия обязана проверяться').toBe(true);
  });

  it('молчание разрешено только там, откуда не выпускают', () => {
    // РАЗДЕЛЕНИЕ, которое сторож выучил на себе, причём дважды.
    //
    // Пропуск законен там, откуда выпуск физически невозможен: нет `gh` либо у него нет
    // доступа к GitHub. Ни создать выпуск, ни поставить описание оттуда нельзя, и молчание
    // ничего не скрывает.
    //
    // А если права ЕСТЬ, а выпуски прочитать не вышло — это отказ САМОГО СТОРОЖА, и он
    // обязан быть красным: иначе следующая забытая версия пройдёт мимо.
    if (выпуски) return;
    expect(
      можноВыпускать,
      `права на GitHub есть, а выпуски прочитать не вышло: ${почемуМолчим}. `
      + 'Сторож слеп — чинить его, а не выпускать вслепую',
    ).toBe(false);
    expect(почемуМолчим, 'выпуски не прочитаны, а причина не названа').toBeTruthy();
  });
});
