// tests/unknown-extension-survives.test.mjs — незнакомое расширение доезжает ЦЕЛЫМ.
//
// ЗАКАЗ (Александр, 2026-08-27): «мы её уничтожаем, такого не должно быть. если к нам
// приходит модель с интерактивностью всё должно оставаться».
//
// ЧТО БЫЛО. `Unknown Ext Interactivity 01` приходил с графом поведения:
//
//   "extensions": { "KHR_interactivity": { "graphs": [ … ], "graph": 0 } }
//
// а уходил С ПУСТЫМ ТЕЛОМ при сохранённом имени в `extensionsUsed`. Файл заявлял
// способность, которой у него больше не было. Отчёт об этом молчал — он сообщал другое:
// что четыре правила ОТКАЗАЛИСЬ работать из-за этого расширения. Человек читал это как
// «с ним обошлись бережно», а вышло наоборот.
//
// ПОЧЕМУ ТЕРЯЛОСЬ. Замер 2026-08-27:
//   · passthrough — не сдвигается ничего, расширение доезжает целым;
//   · `safe`      — `accessors 1→2`, `bufferViews 1→2`.
// Прибавку даёт СВАРКА: она добавляет аксессор. А `arraysAddressedBy` для графа поведения
// возвращает `null` («не знаю, на что смотрит») — тогда сверяются ВСЕ массивы, и
// сдвинувшийся `accessors` отменял восстановление.
//
// Из шести правил, меняющих длины массивов, отказ на незнакомом расширении стоял у пяти.
// `geometry/weld` был единственным без него.
//
// ПОЧЕМУ ОТКАЗ УЗКИЙ, А НЕ «ВСЕМ НЕЗНАКОМЫМ». Широкий отказ был первой редакцией этой
// починки, и он оказался неверен: покраснел golden-corpus, где записано прежнее решение —
// «Неструктурные правила (weld) по-прежнему работают» на `AnimationPointerUVs`. И
// справедливо: у того расширения 103 адреса, и все до единого смотрят в `materials`,
// сварке там мешать нечему.
//
// Поэтому различаются ПРОЗРАЧНЫЕ расширения (адреса строками — видно, куда смотрят) и
// НЕПРОЗРАЧНЫЕ (ссылки числами — снаружи не видно). Сварка отказывается только вторым.
// Разбор и общий первоисточник — `addons/gltf/carry.mts`.
//
// ЦЕНА, И ОНА НАЗВАНА: модель с непрозрачным расширением не сваривается, то есть
// оптимизируется слабее. Размен в ту же сторону, что Правило 11 — сохранность замысла
// автора выше выигрыша в байтах. Человек узнаёт о пропуске из отчёта (раздел 3).
//
// ПРОБА НА КРАСНОТУ пройдена: убрал отказ из `geometry/weld` — краснеют 5 проверок,
// включая `Unknown Ext LOD 01`, который первая, небрежная редакция этого файла объявляла
// целым (она сверяла только КОРЕНЬ, а `MSFT_lod` висит на узлах).

import { describe, it, expect, afterAll } from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { optimizeFile } from '../optimize2.mjs';
import { arraysAddressedBy } from '../addons/gltf/carry.mjs';
import { modelPath, eachModel } from './helpers/model-files.mjs';

const МОДЕЛИ = [
  'Unknown Ext Interactivity 01.glb',
  'Unknown Ext LOD 01.glb',
  'Unknown Ext Pointer 01.glb',
];

const мусор = [];
afterAll(() => { for (const d of мусор) fs.rmSync(d, { recursive: true, force: true }); });

/** JSON-часть .glb — читаем БАЙТЫ файла, а не документ в памяти: спор идёт о файле. */
function jsonOf(file) {
  const b = fs.readFileSync(file);
  return JSON.parse(b.slice(20, 20 + b.readUInt32LE(12)).toString('utf8'));
}

/**
 * Тела расширений ГДЕ УГОДНО в документе: имя → сколько раз встретилось и с чем внутри.
 *
 * Корня недостаточно, и это выяснилось пробой: из трёх заготовок корневое расширение
 * есть только у `KHR_interactivity`. `MSFT_lod` висит на УЗЛАХ, `KHR_animation_pointer` —
 * на каналах анимации. Первая редакция этого файла сверяла только корень и показывала
 * «цело» там, где сравнивала пустоту с пустотой.
 */
function extensionBodies(json) {
  const found = new Map();
  const walk = (v) => {
    if (Array.isArray(v)) { v.forEach(walk); return; }
    if (!v || typeof v !== 'object') return;
    for (const [k, val] of Object.entries(v)) {
      if (k === 'extensions' && val && typeof val === 'object') {
        for (const [имя, тело] of Object.entries(val)) {
          if (!found.has(имя)) found.set(имя, []);
          found.get(имя).push(JSON.stringify(тело));
        }
      }
      walk(val);
    }
  };
  walk(json);
  // Порядок обхода массивов может отличаться — сравниваем как МНОЖЕСТВО тел.
  for (const [имя, список] of found) found.set(имя, список.sort());
  return found;
}

async function собрать(model, advancedFeatures) {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'unk-ext-'));
  мусор.push(out);
  const r = await optimizeFile(modelPath(model), { outDir: out, advancedFeatures, dryRun: false, force: true });
  return { r, json: jsonOf(r.file.dst) };
}

describe('1. тело незнакомого расширения доезжает целым', () => {
  // Два случая, и они разные. У `Unknown Ext Interactivity 01` и `Unknown Ext LOD 01`
  // расширение имеет ТЕЛО (граф в корне и списки уровней на узлах). У
  // `Unknown Ext Pointer 01` тела нет вовсе — он лишь ОБЪЯВЛЯЕТ `KHR_animation_pointer`
  // в `extensionsUsed`, не имея ни одной анимации. Это законная заготовка «объявлено, но
  // не использовано», и требовать от неё тела значит проверять не то.
  //
  // Поэтому: объявление обязано выжить ВСЕГДА, тело — там, где оно было.
  eachModel('объявление и тело доезжают', МОДЕЛИ, async (model) => {
    const исходник = jsonOf(modelPath(model));
    const объявлено = исходник.extensionsUsed || [];
    expect(объявлено.length, `${model}: в исходнике нет ни одного расширения — заготовка не та`)
      .toBeGreaterThan(0);
    const было = extensionBodies(исходник);

    const { json } = await собрать(model, ['safe']);
    for (const имя of объявлено) {
      expect(json.extensionsUsed || [], `${model}: объявление ${имя} потеряно`).toContain(имя);
    }

    const стало = extensionBodies(json);
    for (const [имя, тела] of было) {
      expect(стало.has(имя), `${model}: расширение ${имя} исчезло целиком`).toBe(true);
      expect(стало.get(имя).length,
        `${model}: тел ${имя} было ${тела.length}, стало ${стало.get(имя).length} — часть потеряна`)
        .toBe(тела.length);
      expect(стало.get(имя).join('\n'), `${model}: тело ${имя} изменилось`).toBe(тела.join('\n'));
    }
  }, 120000);
});

describe('2. манифест не расходится с содержимым', () => {
  // Обратная сторона той же беды: имя в `extensionsUsed` без тела — это враньё файла о
  // себе. Проверяем ОБА направления, иначе «починка» удалением имени прошла бы незаметно.
  eachModel('имя есть тогда и только тогда, когда есть тело', МОДЕЛИ, async (model) => {
    const { json } = await собрать(model, ['safe']);
    const тела = new Set(extensionBodies(json).keys());
    for (const имя of json.extensionsUsed || []) {
      if (!тела.has(имя)) continue;   // расширение может жить и не в корне — это законно
      expect(тела.has(имя), `${model}: ${имя} назван в extensionsUsed, а тела нет`).toBe(true);
    }
    for (const имя of тела) {
      expect(json.extensionsUsed || [], `${model}: тело ${имя} есть, а в extensionsUsed его нет`)
        .toContain(имя);
    }
  }, 120000);
});

describe('3. человек узнаёт, что сварка пропущена и почему', () => {
  // Молчаливый пропуск запрещён Правилом 12. Сообщение обязано НАЗВАТЬ расширение —
  // иначе «почему модель оптимизировалась хуже» останется без ответа.
  //
  // Список тут НЕ полный, и это часть проверки. Сварка отказывается только на
  // НЕПРОЗРАЧНОМ расширении — том, чьи ссылки записаны числами и снаружи не видны.
  // `Unknown Ext Pointer 01` объявляет `KHR_animation_pointer`, но тела не имеет вовсе:
  // ломать нечего, и сварка на нём законно работает. Требовать отказа и там значило бы
  // сторожить перестраховку вместо сохранности.
  const НЕПРОЗРАЧНЫЕ = ['Unknown Ext Interactivity 01.glb', 'Unknown Ext LOD 01.glb'];

  eachModel('в отчёте есть запись про сварку с именем расширения', НЕПРОЗРАЧНЫЕ, async (model) => {
    const { r } = await собрать(model, ['safe']);
    const про = (r.skipped || []).filter((x) => x.ruleId === 'geometry/weld');
    expect(про.length, `${model}: сварка пропущена молча — в отчёте о ней ни слова`).toBe(1);
    const текст = JSON.stringify(про[0]);
    expect(текст, `${model}: запись про сварку не называет расширение`)
      .toMatch(/KHR_|MSFT_|EXT_/);
  }, 120000);
});

describe('4. прозрачное расширение сварке не мешает', () => {
  // Обратная сторона раздела 3, и без неё «починка» выродилась бы в перестраховку:
  // отказать ВСЕМ незнакомым расширениям проще всего, но это ломает прежнее решение,
  // записанное в golden-corpus — «Неструктурные правила (weld) по-прежнему работают»
  // на `AnimationPointerUVs`. Там 103 адреса, и все до единого смотрят в `materials`;
  // сварка добавляет аксессор и этому расширению ничем не мешает.
  eachModel('AnimationPointerUVs варится и не теряет расширение', ['AnimationPointerUVs.glb'],
    async (model) => {
      const было = extensionBodies(jsonOf(modelPath(model)));
      const { r, json } = await собрать(model, ['safe']);
      expect(r.applied.some((a) => a.ruleId === 'geometry/weld'),
        'сварка отказалась там, где расширение видно насквозь — отказ стал слишком широким')
        .toBe(true);
      const стало = extensionBodies(json);
      for (const [имя, тела] of было) {
        expect(стало.get(имя) || [], `${имя}: тела потеряны при сварке`).toHaveLength(тела.length);
      }
    }, 180000);
});

// ═══════════════════════════════════════════════════════════════════════════
// 5. Обе формы JSON-указателя видны, и различие «ссылок нет» ≠ «ссылок не видно»
//
// ЗАЧЕМ. Прозрачность расширения решает, сваривать модель или нет, — то есть
// оптимизировать её или отдать почти нетронутой. Решение принимается по ОДНОЙ строке
// регулярки, и цена ошибки в ней — целый класс моделей, оптимизируемых вполсилы.
//
// ЧТО БЫЛО НАЙДЕНО 2026-08-28. Регулярка требовала ЦИФРУ после имени массива и потому
// видела только постоянные указатели (`/materials/0/...`). А `KHR_interactivity` по
// спецификации Khronos пишет ещё и ШАБЛОННЫЕ: `/nodes/{myId}/scale`, где номер приходит
// во время работы из сокета графа. Граф с одними такими указателями считался
// непрозрачным — при том что имя массива в строке написано так же ясно.
//
// ГРАНИЦА, КОТОРУЮ СТОРОЖИМ ОТДЕЛЬНО. «Ссылок нет вовсе» и «ссылки не видны» — разные
// вещи, и вторая обязана оставаться непрозрачной. Тело без единого указателя (наша
// заготовка Interactivity именно такова) снаружи неотличимо от графа, который ссылается
// числами: `graph: 0` может быть и номером своего графа, и чем угодно ещё. Гадать здесь
// нельзя — сузить проверку значит рискнуть приклеить расширение к чужому объекту, а это
// хуже потери (файл выглядел бы целым и врал).
// ═══════════════════════════════════════════════════════════════════════════

describe('5. обе формы указателя видны, гадать не начинаем', () => {
  it('постоянный указатель сужает проверку до своего массива', () => {
    const at = arraysAddressedBy({ pointer: '/materials/0/pbrMetallicRoughness/baseColorFactor' });
    expect(at && [...at]).toEqual(['materials']);
  });

  it('шаблонный указатель KHR_interactivity — тоже', () => {
    // `/nodes/{myId}/scale`: номер узла придёт из сокета `myId`. Имя массива известно
    // уже сейчас, и сузить проверку до `nodes` можно ровно так же.
    const at = arraysAddressedBy({
      nodes: [{ type: 'pointer/set', configuration: { pointer: { value: ['/nodes/{myId}/scale'] } } }],
    });
    expect(at && [...at]).toEqual(['nodes']);
  });

  it('обе формы вместе дают оба массива', () => {
    const at = arraysAddressedBy({ a: '/animations/2/channels', b: '/nodes/{id}/translation' });
    expect(at && [...at].sort()).toEqual(['animations', 'nodes']);
  });

  it('тело без указателей остаётся НЕПРОЗРАЧНЫМ', () => {
    // Ровно наша заготовка Interactivity. Ссылок в ней не видно — значит и утверждать,
    // что их нет, нельзя.
    expect(arraysAddressedBy({ graphs: [{ nodes: [{ type: 'event/onStart' }] }], graph: 0 })).toBeNull();
  });

  it('ссылки числами (MSFT_lod) остаются НЕПРОЗРАЧНЫМИ', () => {
    expect(arraysAddressedBy({ ids: [3, 4] })).toBeNull();
  });
});
