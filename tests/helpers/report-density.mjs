//
// Вынесено из tests/report-density.test.mjs по заданию «сочетания фич»: сторож гоняет
// десятки наборов флагов, а не четыре, и дублировать функцию в двух файлах нельзя.
// Здесь живут ПОРТОГ И ФУНКЦИЯ; корпуса и наборы флагов остаются в тестах, которые
// решают, ЧТО гонять.
//
// Суть: дефект «толпа одинаковых строк» не должен возвращаться с каждой новой фичей.
// Правило, которое обходит список (текстуры, меши, атрибуты, узлы), обязано вернуть
// ОДНУ запись на класс случаев, а не запись на элемент. Больше трёх записей с одним
// messageId в одном отчёте — нарушение (кроме белого списка engine.skipped.line).
//
// Три — не священное число, а запас: две-три однотипные строки читаются нормально,
// десяток уже нет. Если правило порог не проходит — НЕ поднимать порог, а записать
// находку в отчёт: чинить будет основной агент.

// Единственный белый список — engine.skipped.line, «Заголовок правила — причина».
// Их столько, сколько невключённых фич (до восьми), но каждая называет СВОЮ фичу —
// это перечень выбора, а не повтор одного и того же. Белый список явный и не
// пополняется, чтобы тест позеленил: новая запись — решение основного агента.
export const DENSITY_WHITELIST = new Set(['engine.skipped.line']);

// Порог: больше трёх записей с одним messageId в одном отчёте — красный.
export const DENSITY_LIMIT = 3;

/**
 * Нарушения плотности одного отчёта: [[messageId, count], ...] для messageId,
 * повторённых чаще DENSITY_LIMIT и не входящих в белый список. Считает ВСЕ
 * списки отчёта, включая validation: записи проверки несут тот же рецепт
 * i18n.text.messageId (addons/gltf/index.mjs, vp()).
 */
export function densityViolations(result) {
  const counts = new Map();
  for (const list of [result.applied, result.skipped, result.findings, result.validation]) {
    for (const rec of list) {
      const id = rec.i18n?.text?.messageId;
      if (!id || DENSITY_WHITELIST.has(id)) continue;
      counts.set(id, (counts.get(id) || 0) + 1);
    }
  }
  return [...counts.entries()].filter(([, n]) => n > DENSITY_LIMIT);
}
