// tests/budget-doc.test.mjs — сверка площадок и документа, который называет их источники.
//
// ПОВОД (ревизия 2026-09-01, проход П4). `docs/БЮДЖЕТЫ_источники.md` — это документ, ради
// которого заведено правило «числа без источника не пишутся»: каждый порог площадки обязан
// иметь там цитату из первоисточника. Документ разошёлся с профилями молча, и три раза
// по-разному:
//
//   1. Колонка «куда пошло» у чисел Khronos называла профиль `threejs`. Профиля с таким
//      именем нет с 2026-08-09, когда движок и цель развели на две оси: три.js стал
//      ДВИЖКОМ, а числа живут в ПРОЧЕРКЕ (`profiles/_none.json`).
//   2. Порог Shopify «4 МБ» был помечен `warn`, хотя в профиле такого порога нет вовсе.
//   3. Прочерк назван «12 МБ» в прозе — при том, что таблица ВЫШЕ, в этом же документе,
//      говорит 5 МБ. Документ противоречил сам себе.
//
// ЧТО СТЕРЕЖЁМ:
//   1. Профиль, названный в документе, существует. Ловит класс (1) — переименование или
//      удаление площадки, о котором документ не узнал.
//   2. У каждой существующей площадки есть свой раздел. Ловит обратное: площадку завели,
//      а источники её чисел не записали — то есть ровно нарушение правила «числа без
//      источника не пишутся».
//
// ЧЕГО ЭТОТ СТОРОЖ НЕ ЛОВИТ, и это сказано честно: СОГЛАСИЯ ЧИСЕЛ. Единицы в документе
// человеческие («30 ГБ», «5120 КБ»), в профиле машинные (`30720`, `5`), и сверять их
// автоматически значило бы писать разбор единиц, который сам станет источником ошибок.
// Класс (2) и (3) остаются работой ревизии глазами. Сторож закрывает то, что закрывается
// надёжно, и не делает вида, что закрывает остальное.
//
// ПРОБА НА КРАСНОТУ (пройдена 2026-09-01): вернул «threejs» в колонку «куда пошло» —
// краснеет раздел 1 и называет несуществующий профиль; убрал заголовок «### VNTANA» —
// краснеет раздел 2 и называет площадку без источников.

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ДОК = 'docs/БЮДЖЕТЫ_источники.md';
const текст = fs.readFileSync(path.join(root, ДОК), 'utf8');

/** Площадки: id файла и заголовок, под которым площадка известна человеку. */
const площадки = fs.readdirSync(path.join(root, 'profiles'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => {
    const j = JSON.parse(fs.readFileSync(path.join(root, 'profiles', f), 'utf8'));
    return { id: j.id, title: j.title || j.id, enabled: j.enabled !== false };
  });

describe('документ источников не называет несуществующих площадок', () => {
  // Ищем в документе слова, похожие на id профиля, среди известных нам чужих имён. Список
  // намеренно узкий: это не поиск любых опечаток, а сторож против ПЕРЕЖИВШЕГО переезд
  // имени. `threejs` попал сюда потому, что был профилем и перестал им быть.
  const бывшие = ['threejs', 'model-viewer', 'quest', 'mobile'];
  const живые = new Set(площадки.map((p) => p.id));

  for (const имя of бывшие) {
    it(`«${имя}» не выдаётся за площадку`, () => {
      if (живые.has(имя)) return; // стало настоящей площадкой — вопрос снят
      // Упоминание в разделе «Что было выброшено» законно: там как раз пишут, чего больше
      // нет. Ищем в остальном тексте.
      // Второе законное упоминание: имя, названное ДВИЖКОМ (`engines/threejs.json`), —
      // это не площадка, а другая ось (ARCHITECTURE.md §4g). Вычитаем и его: первая
      // редакция этой проверки покраснела ровно на такой строке, и покраснела зря.
      const до = текст.split('## Что было выброшено при сверке')[0]
        .split(`engines/${имя}.json`).join('');
      const строки = до.split('\n').filter((l) => l.includes(имя) && !l.trimStart().startsWith('*'));
      expect(
        строки,
        `${ДОК} называет «${имя}» как площадку, а такого профиля нет. `
        + 'Движок и цель — две разные оси (ARCHITECTURE.md §4g): проверить, не имелся ли в виду прочерк (_none).',
      ).toEqual([]);
    });
  }
});

describe('у каждой площадки есть источники её чисел', () => {
  for (const p of площадки.filter((x) => x.enabled)) {
    it(`${p.title} — свой раздел в документе`, () => {
      // Заголовок раздела пишется человеческим названием площадки, а не id файла: документ
      // читают глазами. Достаточно, чтобы название встречалось в заголовке уровня ###.
      const заголовки = [...текст.matchAll(/^### (.+)$/gm)].map((m) => m[1]);
      expect(
        заголовки.some((h) => h.includes(p.title)),
        `Площадка «${p.title}» есть в profiles/, а раздела с её источниками в ${ДОК} нет. `
        + 'Правило проекта: числа без источника не пишутся — завести раздел с цитатами из первоисточника.',
      ).toBe(true);
    });
  }
});
