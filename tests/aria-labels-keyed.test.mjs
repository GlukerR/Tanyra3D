// tests/aria-labels-keyed.test.mjs — подпись для читалки экрана тоже берётся по ключу.
//
// ПОВОД (ревизия 2026-09-01, проход П9). Правило 8 говорит: любой текст, который видит
// человек, живёт в каталоге строк. `aria-label` — это текст, который человек СЛЫШИТ, и
// исключением он не является.
//
// В разметке было 41 такое место и только 33 с ключом. Восемь диалогов представлялись
// читалке ПО-АНГЛИЙСКИ при полностью русском интерфейсе: «Error», «Metadata»,
// «Validation», «Logs», «Batch summary», «Export result», «Your own platform», «Remove
// models». Не заметить это глазами легко — на экране всё было по-русски.
//
// Ключи при этом УЖЕ ЛЕЖАЛИ В КАТАЛОГЕ. `win.error` вообще числился сиротой — единственным
// неиспользуемым ключом из 340, — и сиротой он был именно потому, что место, которому он
// предназначен, писало английский текст руками. У окна удаления ключ стоял СТРОКОЙ НИЖЕ,
// на видимом заголовке (`data-i18n="batch.remove.title"`), а подпись для читалки рядом
// была захардкожена.
//
// ЧТО СТЕРЕЖЁМ: у каждого `aria-label` и `title` с человеческим текстом есть сосед
// `data-i18n-aria` / `data-i18n-title`. Английский текст в самом атрибуте ОСТАЁТСЯ — это
// запасной вариант до того, как отработает перевод, и так же сделано у `win.close`,
// который был единственным правильным примером с самого начала.
//
// ЧЕГО НЕ СТЕРЕЖЁМ: что ключ ПОДХОДЯЩИЙ. Что `win.logs` стоит именно у окна журнала —
// работа глазами; сторож проверяет только, что ключ вообще есть.
//
// ПРОБА НА КРАСНОТУ (пройдена 2026-09-01): убрал `data-i18n-aria` у окна журнала —
// краснеет и называет строку и текст подписи.

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const РАЗМЕТКА = 'ui/index.html';
const строки = fs.readFileSync(path.join(root, РАЗМЕТКА), 'utf8').split(/\r?\n/);

/**
 * Подписи с ЧЕЛОВЕЧЕСКИМ текстом: начинается с заглавной буквы.
 *
 * Служебные значения (`aria-label="×"`, пустые, из одного символа) под правило не
 * подпадают — их не переводят. Признак грубый, но он и отделяет фразу от значка.
 */
function безКлюча(атрибут, ключевой) {
  const плохие = [];
  строки.forEach((строка, i) => {
    const re = new RegExp(`\\s${атрибут}="([A-ZА-Я][^"]*)"`, 'g');
    for (const [, текст] of строка.matchAll(re)) {
      if (строка.includes(ключевой)) continue;
      плохие.push(`${РАЗМЕТКА}:${i + 1} → ${атрибут}="${текст}"`);
    }
  });
  return плохие;
}

describe('Правило 8 распространяется и на то, что человек слышит', () => {
  it('у каждого aria-label есть ключ data-i18n-aria', () => {
    expect(
      безКлюча('aria-label', 'data-i18n-aria'),
      'Подпись для читалки экрана без ключа: при русском интерфейсе она будет прочитана по-английски. '
      + 'Добавить data-i18n-aria="ключ" рядом, оставив английский текст запасным вариантом (образец — win.close).',
    ).toEqual([]);
  });

  it('у каждого title есть ключ data-i18n-title', () => {
    expect(
      безКлюча('title', 'data-i18n-title'),
      'Всплывающая подсказка без ключа — тот же случай, что и aria-label: человек её ВИДИТ.',
    ).toEqual([]);
  });

  it('проверять было что (разметка разобралась)', () => {
    // Атрибуты переименовали или разметку перестроили — сторож стал бы зелёным и пустым.
    const всего = строки.filter((l) => /\saria-label="/.test(l)).length;
    expect(всего, 'в разметке не нашлось ни одного aria-label — разбор сломался').toBeGreaterThan(20);
  });
});
