// умолчанию.
//
// Опция появилась 2026-08-29, документ правился и после — значит дело не в спешке, а в
// том, что забыть было НЕЧЕМУ помешать.
//
// ЧТО СТЕРЕЖЁМ: каждый id из `ADVANCED_FEATURES` назван в таблице возможностей. Список
// берётся у движка, а не переписывается сюда — переписанный разошёлся бы ровно так же,
// как разошлась таблица (тот же приём, что в `tests/ui-source-badges.test.mjs`, раздел 2).
//
// ЧЕГО НЕ СТЕРЕЖЁМ: что описание ВЕРНО. Проверяемо только наличие; правдивость текста —
// работа ревизии глазами.
//
// ПРОБА НА КРАСНОТУ (пройдена 2026-09-01): убрал строку про `strip-dead-interactivity` —
// краснеет и называет опцию.

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import gltfAddon from '../addons/gltf/index.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ДОК = 'docs/ЧТО_УМЕЕТ.md';
const текст = fs.readFileSync(path.join(root, ДОК), 'utf8');

const ОПЦИИ = Object.keys(gltfAddon.ADVANCED_FEATURES);

describe('таблица возможностей знает про все опции движка', () => {
  it('список опций у движка вообще получен', () => {
    // Движок переименовал поле — сторож стал бы зелёным и пустым.
    expect(ОПЦИИ.length, 'ADVANCED_FEATURES пуст — сторожу нечего сверять').toBeGreaterThan(10);
  });

  for (const id of ОПЦИИ) {
    it(`${id} — назван в ${ДОК}`, () => {
      expect(
        текст.includes(id),
        `Опция «${id}» есть у движка, а в ${ДОК} про неё ни строчки. `
        + 'Документ отвечает на вопрос «что программа умеет» — опция, которой в нём нет, для читателя не существует. '
        + 'Дописать строку в таблицу возможностей.',
      ).toBe(true);
    });
  }
});
