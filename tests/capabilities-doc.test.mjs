// вопрос «что программа умеет». Из шестнадцати опций движка в нём было описано
// пятнадцать. Непрописанной оказалась `strip-dead-interactivity` — и именно она из всех
// шестнадцати самая ответственная: это ОДНО ИЗ ЧЕТЫРЁХ мест, где мы вообще удаляем
