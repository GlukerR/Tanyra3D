// tests/viewer-contract.test.mjs — шов между обвязкой и движком остаётся швом.
//
// ЗАЧЕМ. `ui/viewer/contract.ts` заведён затем, чтобы «движок можно подменить» проверял
// компилятор, а не живая модель. К 2026-09-05 выяснилось, что проверять ему было нечего
// сразу с двух сторон:
//
//   1. Реализация в дереве ОДНА. Интерфейс, вырезанный из единственного класса,
//      согласуется с ним при любом составе — хоть пустой.
//   2. Обвязка обходила контракт приведением типа прямо в месте вызова:
//      `(this.left?.viewer as { densityRange?: () => … })?.densityRange?.()`. Приведение
//      значит «поверь мне», и компилятор верил. Так мимо шва прошли СЕМЬ вызовов и вместе
//      с ними три возможности целиком: плашка о долгой работе, общая шкала плотности и
//      четвёртый режим показа.
//
// Первую слепоту снимает вторая реализация — заглушка `tests/contract/stub-viewer.ts`,
// её собирает `tsconfig.contract.json` на каждом `npm run typecheck` и в CI. Вторую —
// этот файл: приведения из обвязки убраны, и здесь стоит сторож, чтобы они не вернулись.
//
// ПОЧЕМУ СТОРОЖ ЧИТАЕТ ИСХОДНИК, А НЕ ЗАПУСКАЕТ. Проверяется то, чего в коде быть НЕ
// должно, — а не поведение. Приведение типа исчезает при сборке бесследно: в собранном
// `.js` его нет вовсе, и никакой запуск его не увидит. Видно его только в исходнике.
//
// ПРОБА НА КРАСНОТУ (пройдена 2026-09-05): вернул одно приведение в `_применитьOnBusy` —
// первая проверка назвала строку; убрал `diffScale` из заглушки — третья назвала метод.

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const КОРЕНЬ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const читать = (относительный) => fs.readFileSync(path.join(КОРЕНЬ, относительный), 'utf8');

const ОБВЯЗКА = 'ui/viewer/index.ts';
const КОНТРАКТ = 'ui/viewer/contract.ts';
const ЗАГЛУШКА = 'tests/contract/stub-viewer.ts';
const РЕАЛИЗАЦИЯ = 'ui/viewer/viewer.ts';

/**
 * Имена членов `ViewerLike` из контракта.
 *
 * Разбор по строкам, а не через TypeScript API: нужен список имён, а не дерево. Член —
 * строка ровно с двумя пробелами отступа, начинающаяся с имени, за которым идёт `(`, `?(`,
 * `:` или `?:`. Комментарии отсеиваются сами: они начинаются со звёздочки или косой.
 */
function членыКонтракта(текст) {
  const начало = текст.indexOf('export interface ViewerLike {');
  expect(начало, 'в контракте нет интерфейса ViewerLike').toBeGreaterThan(-1);
  const тело = текст.slice(начало, текст.indexOf('\n}', начало));
  const имена = [];
  for (const строка of тело.split('\n')) {
    const m = /^ {2}([A-Za-z_$][\w$]*)\??\s*[(:]/.exec(строка);
    if (m) имена.push(m[1]);
  }
  return имена;
}

describe('шов между обвязкой и движком', () => {
  it('обвязка не приводит вьюер к объектному типу', () => {
    const текст = читать(ОБВЯЗКА);
    const виноватые = текст
      .split('\n')
      .map((строка, i) => [i + 1, строка])
      .filter(([, строка]) => /\bas\s*\{/.test(строка));
    expect(
      виноватые.map(([n, s]) => `${ОБВЯЗКА}:${n}: ${s.trim()}`),
      'приведение к объектному типу обходит контракт: подпись нужно завести в contract.ts',
    ).toEqual([]);
  });

  it('обвязка знает движок только по контракту', () => {
    const текст = читать(ОБВЯЗКА);
    // Единственный тип, которым названы поля `viewer` у слотов. Появись рядом импорт
    // класса `Viewer` — обвязка снова знала бы конкретный движок.
    expect(текст).toMatch(/declare viewer: ViewerLike \| null/);
    // Класс движка обвязка ЗНАЕТ — иначе его нечем было бы завести в таблицу `VIEWERS`.
    // Но знает ровно там: одно упоминание, в одной строке таблицы. Второе означало бы, что
    // где-то в обвязке снова появилась переменная конкретного движка.
    expect(текст.match(/new Viewer\(/g) ?? [], 'движок создаётся только в таблице VIEWERS')
      .toHaveLength(1);
    // Проверяется ЗАВИСИМОСТЬ, а не слово: `THREE` в этом файле встречается — в шапке,
    // где объяснено, почему тип значения в `VIEWERS` именно `ViewerLike`. Комментарий про
    // три.js законен, импорт три.js — нет.
    expect(текст, 'обвязка не должна зависеть от три.js').not.toMatch(/from ['"]three/);
  });

  it('заглушка объявляет контракт целиком', () => {
    const заглушка = читать(ЗАГЛУШКА);
    expect(заглушка).toMatch(/class StubViewer implements ViewerLike/);
    // Необязательные члены компилятор у заглушки не спросит — их отсутствие законно.
    // Но заглушка тем и ценна, что проходит контракт ЦЕЛИКОМ: пропущенный член значит,
    // что подпись никто не проверил на движке без три.js.
    // Ищется ОБЪЯВЛЕНИЕ, а не слово. Первая редакция сторожа искала слово — и молчала,
    // когда член из заглушки убирали: имя оставалось в её же шапке, где перечислены семь
    // вызовов. Сторож, который зеленеет от комментария, — не сторож (проба 2026-09-05).
    const объявлен = (имя) =>
      new RegExp(`^ {2}(?:readonly |private |async |override )*${имя}[(:?\\s=]`, 'm').test(заглушка);
    const пропущены = членыКонтракта(читать(КОНТРАКТ)).filter((имя) => !объявлен(имя));
    expect(пропущены, 'заглушка отстала от контракта — эти члены никем не проверены').toEqual([]);
  });

  it('всё, что зовёт обвязка, есть и в контракте, и в настоящем движке', () => {
    const контракт = читать(КОНТРАКТ);
    const движок = читать(РЕАЛИЗАЦИЯ);
    // Семь вызовов, ушедших мимо шва 2026-09-05. Список поимённый и намеренно: он
    // называет ровно ту работу, которую сторож охраняет, и читается как её перечень.
    const семь = [
      'setOnBusy', 'densityRange', 'setDensityScale',
      'textureRefs', 'setDiffReference', 'useDiffStore', 'diffScale',
    ];
    const вКонтракте = членыКонтракта(контракт);
    expect(семь.filter((имя) => !вКонтракте.includes(имя))).toEqual([]);
    expect(семь.filter((имя) => !new RegExp(`^ {2}${имя}\\(`, 'm').test(движок))).toEqual([]);
  });

  it('шов проверяется компилятором на каждом typecheck', () => {
    const пакет = JSON.parse(читать('package.json'));
    expect(пакет.scripts.typecheck, 'без этого проекта заглушка не собирается никем')
      .toContain('tsconfig.contract.json');
    const проект = читать('tsconfig.contract.json');
    expect(проект).toContain('"noEmit": true');
    expect(проект).toContain('tests/contract/*.ts');
  });
});
