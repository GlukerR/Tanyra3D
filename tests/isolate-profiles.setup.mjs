// tests/isolate-profiles.setup.mjs — набор не смотрит в папку своих профилей человека.
//
// Заведено 2026-08-13 по настоящему падению. Тест engine-target-split сравнивал число
// ВСТРОЕННЫХ профилей (`profiles/*.json` в дереве) с длиной `listPlatforms()`, а та с
// 12 августа читает ещё и пользовательскую папку. На CI она пуста — тест зелёный. На
// машине Александра, который завёл свою площадку в установленной программе, ждали 1,
// получили 2.
//
// Хуже самого падения то, что оно означало: набор ЧИТАЛ рабочие данные человека. Любой
// тест, дошедший до `listPlatforms`, `loadProfile` или `explainResult`, зависел от того,
// что лежит в `%APPDATA%/Tanyra3D/profiles` — то есть от машины, а не от кода. Тест,
// результат которого зависит от машины, не сторож.
//
// Изоляция стоит одной строки: переменная TANYRA3D_PROFILES_DIR перекрывает путь (та же,
// которой пользуется тот, кто держит профили на общем диске). Тесты про сами свои
// профили (`user-profiles`, `profile-form`) подменяют её своей временной папкой в
// beforeEach — это по-прежнему работает, они перекрывают уже перекрытое.
//
// setupFiles, а не globalSetup: globalSetup идёт в отдельном процессе, и его process.env
// до рабочих потоков не доезжает. Этот файл выполняется в КАЖДОМ потоке перед тестами.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

// Папка одна на весь прогон и создаётся пустой. Не удаляем в конце: она в системной
// временной папке, а держать в setup-файле ещё и уборку значит гадать, кто уйдёт
// последним из нескольких потоков.
const dir = path.join(os.tmpdir(), 'tanyra3d-tests-profiles');
fs.mkdirSync(dir, { recursive: true });
process.env.TANYRA3D_PROFILES_DIR = dir;
