// 5. Скрытая строка ничего не просит
// ═══════════════════════════════════════════════════════════════════════════
//
// Находка ревью 2026-09-01, и это ровно Правило 12 наизнанку: не «показанная галочка не
// работает», а «СКРЫТАЯ работает». Подчинённая строка «Убирать лишнюю развёртку»
// пряталась классом `hidden` при снятом `safe`, состояние самой галочки при этом не
// менялось — и снятая когда-то галочка продолжала слать движку `keep-unused-uv` с экрана,
// где её уже не было. Сборка шла не так, как показывала панель.
//
// Чинится это не сверкой двух условий, а тем, что просьба ВЫВОДИТСЯ из видимости: одно
// условие разойтись само с собой не может. Раздел сторожит оба конца этой связи.
//
// Заодно исправлена причина, по которой строка вообще пряталась. Замер 2026-09-01:
// `structure/prune-final` включается от safe, склейки ИЛИ сжатия геометрии и без `safe`
// тоже сносит развёртку без картинок. Значит вопрос живой и там, а привязка к одному
// `safe` прятала от человека работающую возможность.

describe('скрытая подчинённая строка ничего не просит', () => {
  it('просьба про развёртку выводится из ВИДИМОСТИ строки, а не из одной галочки', () => {
    const тело = block('const keepingUnusedUv = () => {');
    expect(тело, 'keepingUnusedUv перестал смотреть, видна ли строка — скрытая галочка снова просит')
      .toMatch(/hidden/);
  });

  it('видимость строки решает ЧИСТКА В ЦЕЛОМ, а не один флажок safe', () => {
    const тело = block('function toggleUvSubRow() {');
    expect(тело, 'видимость снова решается на месте, мимо общего условия')
      .toMatch(/чисткаБудет/);

    // Само условие обязано знать про все три способа запустить чистку данных вершин:
    // `structure/prune-final` включается от safe, склейки ИЛИ сжатия геометрии.
    const условие = block('function чисткаБудет(): boolean {');
    for (const признак of ['ext-safe', 'ext-join', 'geometryChoice']) {
      expect(условие, `условие видимости забыло про ${признак} — строка спрячется там, где чистка идёт`)
        .toContain(признак);
    }
  });

  it('видимость пересчитывается на ЛЮБОЙ смене опции', () => {
    // Раньше пересчёт висел только на флажке `safe`. Смена кодека его не трогала — и
    // строка оставалась спрятанной ровно тогда, когда становилась нужной.
    expect(block('function onOptionChanged() {'), 'onOptionChanged перестал пересчитывать строку развёртки')
      .toMatch(/toggleUvSubRow\(\)/);
  });
});
