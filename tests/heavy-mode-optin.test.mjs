// tests/heavy-mode-optin.test.mjs — четвёртый способ показа включается человеком, а не нами.
//
// Александр 2026-09-05: «надо сделать что бы основными режимами были только 3. а четвёртый
// был только при включении его в настройках… Это тяжёлый мод и он не должен быть для всех и
// для всего. на слабых пк он вообще не пойдёт».
//
// Причин две, и обе настоящие:
//
//   ПО СМЫСЛУ. Первые три отвечают на вопрос «как выглядит эта модель» и работают на любой.
//   Четвёртый отвечает на другой вопрос — «что в ней изменила сборка», — и без второй
//   модели бессмыслен.
//
//   ПО ЦЕНЕ. Он читает КАЖДУЮ карту обеих моделей пиксель за пикселем и считает по ним
//   схожесть структуры. На тяжёлой модели это десятки мегабайт и заметные секунды даже на
//   сильной машине.
//
// ГЛАВНОЕ, ЧТО СТЕРЕЖЁТ ЭТОТ ФАЙЛ: выключено — значит кнопки НЕТ. Не погашена. Погашенная
// кнопка без объяснения читается как поломка, а показанная обязана работать (Правило 12);
// объяснение живёт там, где человек её включает, — рядом с галочкой в настройках.
//
// Проверки статические — по тому же образцу, что `export-window.test.mjs`: поведение живёт
// в браузере, а сюда смотрит сторож за местами, откуда беда возвращается. Сквозная проверка
// сделана руками в живом приложении: галочка снята — кнопки нет; поставлена — появилась и
// работает; снята при включённом режиме — показ вернулся к материалам файла.

import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { readSource } from './helpers/source-files.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HTML = fs.readFileSync(path.join(ROOT, 'ui', 'index.html'), 'utf8');
const APP = readSource('ui/app');
const EN = fs.readFileSync(path.join(ROOT, 'ui', 'locales', 'en.js'), 'utf8');
const RU = fs.readFileSync(path.join(ROOT, 'translations', 'ru.js'), 'utf8');

/** Разметка одной кнопки по её id — вместе со всеми классами. */
function кнопка(id) {
  const m = new RegExp(`<button[^>]*id="${id}"[^>]*>`).exec(HTML);
  expect(m, `в разметке нет кнопки #${id}`).toBeTruthy();
  return m[0];
}

describe('тяжёлый способ показа включается в настройках', () => {
  it('основных кнопок показа три, четвёртая скрыта в разметке', () => {
    for (const id of ['display-wire', 'display-clay', 'display-file']) {
      expect(кнопка(id), `#${id} — основной способ показа, он не прячется`)
        .not.toMatch(/class="[^"]*\bhidden\b/);
    }
    // Класс стоит В РАЗМЕТКЕ, а не наводится из кода при запуске: иначе кнопка успевала бы
    // мигнуть до первого кадра у всех, включая тех, кто её не включал.
    expect(кнопка('display-texdiff'), 'четвёртая кнопка обязана быть скрытой по умолчанию')
      .toMatch(/class="[^"]*\bhidden\b/);
  });

  it('в настройках есть галочка и сказано, чем за неё платишь', () => {
    expect(HTML).toMatch(/<input[^>]*type="checkbox"[^>]*id="setting-texdiff"/);
    // Обе половины обязательны: подпись говорит, ЧТО режим даёт, пояснение — ЧЕМ за это
    // платишь. Без второй человек включит его на слабой машине и решит, что приложение
    // зависло.
    expect(HTML).toContain('data-i18n="menu.settings.texdiff"');
    expect(HTML).toContain('data-i18n="menu.settings.texdiff.hint"');
    for (const [имя, каталог] of [['en', EN], ['ru', RU]]) {
      for (const ключ of ['menu.settings.viewport', 'menu.settings.texdiff', 'menu.settings.texdiff.hint']) {
        expect(каталог, `в каталоге ${имя} нет ключа ${ключ}`).toContain(`'${ключ}'`);
      }
    }
  });

  it('выбор помнится между запусками', () => {
    // Тем же способом, что язык (`tanyra.lang` в ui/i18n.ts): человек, включивший тяжёлый
    // режим однажды, не должен включать его каждое утро.
    expect(APP).toMatch(/localStorage\.getItem\(ТЯЖЁЛЫЙ_РЕЖИМ\)/);
    expect(APP).toMatch(/localStorage\.setItem\(ТЯЖЁЛЫЙ_РЕЖИМ/);
    expect(APP).toMatch(/ТЯЖЁЛЫЙ_РЕЖИМ = 'tanyra\.texdiff'/);
    // Приватный режим браузера бросает на обоих обращениях — а настройка не повод не
    // запуститься. Тот же приём, что в ui/i18n.ts.
    expect(APP.match(/catch \(e\) \{ return false; \}/g) ?? []).not.toHaveLength(0);
  });

  it('снятая галочка убирает кнопку и выводит из режима', () => {
    const тело = /function применитьTexdiff\([\s\S]*?\n {2}\}/.exec(APP);
    expect(тело, 'применитьTexdiff пропала — кнопкой больше никто не управляет').toBeTruthy();
    const код = тело[0];
    expect(код).toMatch(/displayTexdiffBtn\?\.classList\.toggle\('hidden', !on\)/);
    // Иначе человек остался бы в режиме, кнопки которого больше нет: выйти нечем, а
    // красная модель на экране выглядела бы поломкой.
    expect(код).toMatch(/getDisplayMaterial\?\.\(\) === 'texdiff'/);
    expect(код).toMatch(/setDisplayMaterial\('file'\)/);
  });

  it('сам способ показа из движка НЕ удалён', () => {
    // Галочка прячет кнопку, а не вырезает возможность: список режимов в контракте
    // остаётся полным, иначе включённая галочка вела бы в никуда (Правило 12).
    expect(readSource('ui/viewer/contract'))
      .toMatch(/DISPLAY_MODES = \['wire', 'clay', 'file', 'texdiff'\]/);
  });
});
