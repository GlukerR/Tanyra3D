// desktop/main.cjs — оболочка настольного приложения.
//
// Зачем она вообще нужна. Программа и без неё работает: `npm start` поднимает сервер и
// открывает страницу в браузере. Но до этого человеку надо поставить Node, склонировать
// репозиторий, выполнить четыре команды в терминале и на Windows обойти запрет на
// выполнение сценариев. Художник, ради которого всё это писалось, до второго шага не
// доходит. Оболочка убирает ровно эти шаги и больше ничего: внутри тот же сервер, та же
// страница, тот же движок.
//
// Почему оболочка тонкая. Она не знает ни про glTF, ни про правила, ни про отчёты —
// только запускает сервер и показывает его в окне. Это продолжение того же разделения,
// что между ядром и аддоном: у окна нет причин знать, что оно показывает.
//
// CommonJS, а не ESM: в package.json стоит "type": "module", и главный процесс Electron
// надёжнее держать в .cjs, чем полагаться на поддержку ESM в конкретной версии.

const { app, BrowserWindow, shell, dialog } = require('electron');
const { fork } = require('node:child_process');
const path = require('node:path');
const fs = require('node:fs');
// Свой адрес или чужой — отдельным модулем: он не зависит от electron и потому
// проверяется тестами напрямую, а не пересказом по исходнику.
const { isOwnPage, isExternalWeb } = require('./url-policy.cjs');

// Корень спрашиваем у Electron, а не вычисляем сами. Он разный в трёх случаях —
// запуск из исходников, собранный пакет с asar, собранный без него, — и угадывать
// его руками значит ошибиться в одном из трёх. Первая версия так и ошиблась:
// вычисляла путь внутрь app.asar, которого нет, потому что архив выключен.
const ROOT = app.getAppPath();
const SERVER = path.join(ROOT, 'server.mjs');

// Куда положен ktx. В собранном пакете — в ресурсы (см. extraResources в package.json),
// при запуске из исходников — привычная `.tools/` в корне.
const TOOLS_DIR = app.isPackaged
  ? path.join(process.resourcesPath, 'tools')
  : path.join(__dirname, '..', '.tools');

/**
 * Одна программа — один запущенный экземпляр.
 *
 * Найдено Александром 2026-08-21: «я могу кучи окон запустить одного и того же
 * приложения. нет ошибки что уже приложение запущено».
 *
 * Лишнее окно — не главная беда. Каждый экземпляр поднимает СВОЙ движок, а движок на
 * старте очищает рабочую папку (`ensureEmptyDir` для uploads/ и results/ в server.mts).
 * Папка у всех одна: `app.getPath('userData')/work`. Значит второй запуск СТИРАЕТ
 * загруженные модели и собранные результаты первого — прямо посреди работы, без единого
 * слова. Плюс второй процесс движка, который никто не остановит.
 *
 * Ровно эту беду ревью 2026-08-10 (P0.2.2) уже находило и чинило — но только для клика
 * по значку в доке macOS (`app.on('activate')`). Через парадную дверь, повторным
 * запуском программы, она осталась открытой.
 *
 * Замок берётся ДО `whenReady` и до запуска движка. Возьми его позже — второй экземпляр
 * успел бы поднять сервер и вычистить папку прежде, чем понял, что он лишний.
 *
 * Второму экземпляру мы НЕ показываем ошибку, а показываем окно первого. Человек, дважды
 * щёлкнувший по значку, хочет открыть программу, а не прочитать, что он щёлкнул дважды;
 * окно, вышедшее вперёд, отвечает на его действие точнее любого сообщения. Своего окна
 * второй экземпляр не создаёт и движок не поднимает — он просто уходит.
 */
const gotTheLock = app.requestSingleInstanceLock();

if (!gotTheLock) {
  app.quit();
} else {
  app.on('second-instance', () => {
    // Окна нет, а движок работает — значит его закрыли (на macOS это норма, программа
    // живёт без окон). Запуск программы в этом положении означает «покажи её», и
    // единственный честный ответ — открыть окно на ТОМ ЖЕ движке. Раньше здесь стоял
    // молчаливый выход: человек запускал программу и не получал ничего.
    //
    // Второго движка мы всё равно не поднимаем — адрес берётся у работающего.
    if (!mainWindow) {
      if (serverAddress) createWindow(serverAddress);
      return;
    }
    // Свёрнутое окно сначала разворачиваем: `focus()` по свёрнутому не поднимает его,
    // и человек получил бы полное молчание в ответ на запуск.
    if (mainWindow.isMinimized()) mainWindow.restore();
    mainWindow.show();
    mainWindow.focus();
  });
}


let serverProcess = null;
let mainWindow = null;
// Адрес работающего движка. Нужен, чтобы при повторном открытии окна показать ТОТ ЖЕ
// сервер, а не поднимать второй (см. app.on('activate')).
let serverAddress = null;

// Весь вывод движка с начала запуска. Растёт только до открытия окна: дальше сервер
// работает часами, и держать его журнал в памяти незачем.
const serverLog = [];
let collectLog = true;
const pushLog = (chunk) => { if (collectLog) serverLog.push(String(chunk)); };

/** Файл с полным выводом — то, что человек может приложить к сообщению о поломке. */
function saveCrashLog() {
  try {
    const file = path.join(app.getPath('userData'), 'engine-crash.log');
    fs.writeFileSync(file, [
      `Tanyra3D ${app.getVersion()} · ${new Date().toISOString()}`,
      `${process.platform} ${process.arch} · Electron ${process.versions.electron} · Node ${process.versions.node}`,
      `Папка программы: ${ROOT}`,
      `Инструменты: ${TOOLS_DIR} (${fs.existsSync(TOOLS_DIR) ? 'на месте' : 'НЕТ'})`,
      '',
      serverLog.join('') || '(движок не сказал ни слова)',
    ].join('\n'), 'utf8');
    return file;
  } catch {
    return null;      // некуда писать — не повод падать поверх падения
  }
}

/**
 * Ошибка запуска вместе с тем, что успел сказать движок.
 *
 * Без хвоста вывода сообщение бесполезно одинаково для всех: и для человека, который
 * видит только код, и для того, кто чинит. Причина отказа при запуске почти всегда
 * стоит в последних строках — не найден модуль, не сошлась нативная сборка, занят
 * порт, нет прав на папку.
 */
function startupError(headline) {
  const tail = serverLog.join('').trim().split('\n').slice(-12).join('\n');
  const file = saveCrashLog();
  return new Error([
    headline,
    tail ? `\nЧто сказал движок:\n${tail}` : '\nДвижок не сказал ничего.',
    file ? `\nПолный отчёт: ${file}` : '',
  ].join('\n'));
}

function startServer() {
  return new Promise((resolve, reject) => {
    const env = {
      ...process.env,
      // Порт выбирает система. Фиксированный занят, если человек уже запустил программу
      // из терминала, — и окно молча не открылось бы.
      PORT: '0',
      // Страница уже показана в окне; второй раз в браузере она не нужна.
      TANYRA_NO_BROWSER: '1',
      // Сервер запускается бинарником Electron. Без этой переменной тот считает себя
      // приложением и не выполняет переданный сценарий. Она же наследуется дальше — в
      // дочерний процесс gltf-transform CLI, который сервер зовёт тем же execPath.
      ELECTRON_RUN_AS_NODE: '1',
    };
    if (fs.existsSync(TOOLS_DIR)) env.TANYRA_TOOLS_DIR = TOOLS_DIR;

    // Куда движку писать загрузки и результаты. Рядом с программой нельзя: установленная
    // в Program Files, она лежит в папке, куда обычному пользователю писать не дают, и
    // сервер падал на первом же mkdir с EPERM, не дойдя до порта. Папка данных
    // пользователя есть на всех трёх системах и всегда доступна на запись.
    env.TANYRA_DATA_DIR = path.join(app.getPath('userData'), 'work');

    const child = fork(SERVER, [], { env, stdio: ['ignore', 'pipe', 'pipe', 'ipc'] });

    // Вывод сервера — в консоль оболочки И в кольцевой буфер.
    //
    // Консоли у оконной программы нет: на Windows её не видит никто, и до 2026-08-09
    // это означало, что при отказе запуска настоящая ошибка пропадала бесследно.
    // Человек получал «сервер завершился с кодом 1» — сообщение, по которому нельзя
    // ни понять причину, ни рассказать о ней тому, кто чинит. Александр так и написал:
    // «вышла ошибка, не удалось запустить движок».
    //
    // Буфер маленький: причина падения при импорте — это последние несколько строк,
    // а не весь журнал. Полный вывод всё равно уходит в файл (см. saveCrashLog).
    child.stdout.on('data', (b) => { process.stdout.write(`[server] ${b}`); pushLog(b); });
    child.stderr.on('data', (b) => { process.stderr.write(`[server] ${b}`); pushLog(b); });

    // Сторож запуска. Гасить его обязательно, а не «Promise уже resolved, и ладно»:
    // startupError() не просто отвергает обещание — он собирает отчёт и ПИШЕТ
    // engine-crash.log. Через тридцать секунд после удачного старта у работающего
    // приложения на диске появлялся файл с сообщением о падении, которого не было.
    // Ревью 2026-08-10 (P0.2.1).
    let startupTimer = null;
    // Обещание решается ОДИН раз, и это не про сам Promise (он и так игнорирует второй
    // вызов), а про побочное действие: startupError() собирает отчёт и ПЕРЕЗАПИСЫВАЕТ
    // engine-crash.log. Без этого флага выход по сторожу выглядел так: сторож пишет
    // верное «не отозвался за 30 секунд», тут же убивает движок, движок выходит — и его
    // обработчик перезаписывает файл строкой «остановился с кодом null», то есть
    // подменяет настоящую причину следствием своей же уборки.
    let settled = false;
    const settle = (fn) => (...args) => {
      if (settled) return;
      settled = true;
      if (startupTimer) { clearTimeout(startupTimer); startupTimer = null; }
      fn(...args);
    };
    const done = settle(resolve);
    // Отказ запуска — значит движок нам не нужен, но он может быть ЖИВ: «не отозвался
    // за тридцать секунд» не то же самое, что «умер». Не убить его здесь — оставить
    // сироту, которая держит порт и память. Дальше по коду его не убьёт никто:
    // stopServer() смотрит на serverProcess, а тот присваивается только после успеха.
    // Ревью 2026-08-10 (D6).
    const fail = settle((e) => {
      if (!child.killed && child.exitCode === null) { try { child.kill(); } catch { /* уже мёртв */ } }
      reject(e);
    });

    // Сервер сам сообщает адрес: порт выдала система, заранее его не знает никто.
    child.on('message', (m) => {
      if (m && m.type === 'listening') done({ child, address: m.address });
    });
    child.on('error', fail);
    child.once('exit', (code) => {
      // Дать последним строкам stderr дойти до нас: 'exit' приходит раньше, чем
      // опустеет труба, и без этой отсрочки в отчёт попадала бы пустота.
      // Сторож гасится сразу, а не через эти 100 мс: иначе при выходе на 29-й секунде
      // успели бы сработать оба и отчётов вышло бы два.
      if (startupTimer) { clearTimeout(startupTimer); startupTimer = null; }
      // Уже решили (успешный старт или сторож, который сам же и убил движок) — молчим:
      // иначе отчёт о падении соберётся поверх настоящей причины. Флаг снимаем ЗДЕСЬ, а
      // не внутри setTimeout: за эти 100 мс сторож успел бы сработать вторым.
      if (settled) return;
      settled = true;
      setTimeout(() => reject(startupError(`Движок остановился с кодом ${code}, не открыв порт`)), 100);
    });

    // Если сервер не отозвался — виснуть в пустом окне хуже, чем сказать вслух.
    startupTimer = setTimeout(() => fail(startupError('Движок не отозвался за 30 секунд')), 30_000);
  });
}

function createWindow(address) {
  mainWindow = new BrowserWindow({
    width: 1440,
    height: 900,
    minWidth: 1024,
    minHeight: 640,
    backgroundColor: '#1b1b1f', // до первой отрисовки — не белая вспышка
    show: false,
    webPreferences: {
      // Странице не нужен доступ ни к Node, ни к файловой системе: она разговаривает с
      // сервером по HTTP, ровно как в браузере. Значит и давать его незачем.
      nodeIntegration: false,
      contextIsolation: true,
    },
  });

  mainWindow.removeMenu();
  mainWindow.once('ready-to-show', () => mainWindow.show());
  mainWindow.loadURL(address);

  // Внешние ссылки (документация, лицензии) — в настоящий браузер, а не подменой
  // страницы приложения: вернуться из неё было бы нечем, меню у окна нет.
  //
  // Наружу отдаём только http и https. `shell.openExternal` передаёт адрес системе, а
  // система знает куда больше схем: `file:` откроет что-нибудь с диска, а на Windows
  // есть схемы, через которые запускаются программы. Список того, что можно, короче и
  // надёжнее списка того, что нельзя. Ревью 2026-08-10 (P1.6).
  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
    if (isExternalWeb(url)) shell.openExternal(url);
    return { action: 'deny' };
  });
  mainWindow.webContents.on('will-navigate', (e, url) => {
    if (isOwnPage(url, address)) return;
    e.preventDefault();
    if (isExternalWeb(url)) shell.openExternal(url);
  });

  mainWindow.on('closed', () => { mainWindow = null; });
}

// Запускаемся ТОЛЬКО с замком. Без этой проверки второй экземпляр всё равно дошёл бы
// сюда: app.quit() до готовности не обрывает выполнение немедленно, а обработчик
// whenReady уже зарегистрирован — движок успел бы подняться и вычистить рабочую папку
// первого. Ради этого замок и брался.
if (gotTheLock) app.whenReady().then(async () => {
  try {
    const started = await startServer();
    serverProcess = started.child;
    serverAddress = started.address;
    collectLog = false;   // запустился — дальше журнал в памяти не нужен
    serverLog.length = 0;
    // Первый обработчик exit был одноразовым сторожем запуска; дальше падение сервера —
    // это уже не «не смог открыться», а «умер на ходу», и говорить надо другое.
    serverProcess.removeAllListeners('exit');
    serverProcess.on('exit', (code) => {
      if (code !== 0 && !app.isQuitting) {
        dialog.showErrorBox('Tanyra3D', `Движок остановился (код ${code}). Закройте окно и запустите программу заново.`);
      }
    });
    createWindow(started.address);
  } catch (e) {
    dialog.showErrorBox('Tanyra3D', `Не удалось запустить движок.\n\n${e.message}`);
    app.quit();
  }

  app.on('activate', () => {
    // macOS: клик по значку в доке при закрытых окнах — обычай платформы.
    //
    // Открываем ОКНО, а не второй движок. Раньше здесь звался startServer(), хотя
    // старый сервер продолжал работать: появлялся второй процесс, который никто не
    // запоминал (в serverProcess он не попадал), при выходе убивался только первый, а
    // главное — каждый сервер на старте чистит uploads/ и results/. Второй стирал
    // данные, с которыми в этот момент работал первый.
    // Ревью 2026-08-10 (P0.2.2).
    if (BrowserWindow.getAllWindows().length === 0 && serverAddress) {
      createWindow(serverAddress);
    }
  });
});

// Сервер — дочерний процесс, сам он не уйдёт. Осиротевший, он держит порт и продолжает
// занимать память после того, как окно закрыто.
function stopServer() {
  if (serverProcess && !serverProcess.killed) {
    serverProcess.kill();
    serverProcess = null;
  }
}

// Рабочие файлы не переживают выход из программы.
//
// Сервер и так чистит uploads/ и results/ на старте, но между сеансами всё лежало на
// диске: закрыл программу в пятницу — и до понедельника гигабайты чужих уже никому не
// нужных сборок занимают место, о котором человек не знает (Александр, 2026-08-13).
// Чистим здесь, а не в сервере: он к этому моменту уже убит, и папка свободна.
//
// Стираем СОДЕРЖИМОЕ work/, а не саму папку: имя каталога сервер ждёт готовым.
// Не удалось (файл занят антивирусом, диск отвалился) — не беда: следующий запуск
// чистит то же самое. Ронять выход из-за уборки нельзя.
function clearWorkDir() {
  const work = path.join(app.getPath('userData'), 'work');
  let entries;
  try { entries = fs.readdirSync(work); } catch { return; }
  for (const entry of entries) {
    try { fs.rmSync(path.join(work, entry), { recursive: true, force: true }); } catch { /* занято */ }
  }
}

app.on('before-quit', () => { app.isQuitting = true; stopServer(); });
app.on('will-quit', () => { stopServer(); clearWorkDir(); });
app.on('window-all-closed', () => {
  // macOS держит приложение живым без окон — там это норма, а не утечка.
  if (process.platform !== 'darwin') app.quit();
});
